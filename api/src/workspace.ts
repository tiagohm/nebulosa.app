import type { ConnectionType } from './connection'
import type { AppDatabase } from './database'
import { errorResponse } from './http'
import type { MountRemoteProtocol } from './mountremotecontrol'

// Workspace of the operators: the saved connections, the observing sites, and the profiles, with their active site,
// equipment, preferences, camera forms, Mount Remote Control bindings, saved framings, and the notifications they read
// or dismissed, persisted in the operational database and shared by every tab and browser. Saved connections are
// definitions only, never the connections the server holds open, and a profile chooses devices and a site without ever
// commanding a device. Ids are generated by the tab that creates a connection, a site, a profile, or a framing,
// so a tab applies its edits at once and writes them after. Every write publishes the record it changed once committed.
// The shapes of the preferences and camera forms belong to the web, which versions them; the server keeps them as they
// come, and checks only revisions and what the schema enforces.

// Preference of a profile kept as one value (profile_preferences).
export type ProfilePreferenceKey =
	| 'telescope'
	| 'guideTelescope'
	| 'skyDisplay'
	| 'skyFraming'
	| 'starDetection'
	| 'starProfile'
	| 'streakDetection'
	| 'imageAnnotation'
	| 'imagePlateSolving'
	| 'imageDisplay'
	| 'imageAstrometry'
	| 'statusBar'
	| 'satelliteFavorites'
	| 'dateTime'
	| 'meridianFlipMonitor'
	| 'meridianFlipExecutor'
	| 'mountDither'

// Form of a physical camera in a profile (profile_camera_settings).
export type ProfileCameraForm = 'exposure' | 'acquisition' | 'plateSolving' | 'autoFocus' | 'tppa' | 'pointingModel' | 'targetCentering' | 'darv' | 'flatWizard' | 'darkLibraryWizard' | 'liveStacking' | 'guiding' | 'display'

// Error codes of the workspace routes.
export type WorkspaceErrorCode = 'conflict' | 'notFound' | 'lastProfile'

// Connection saved by an operator.
export interface SavedConnection {
	// Id of the saved connection.
	readonly id: string
	// Name shown to people.
	readonly name: string
	// Backend the connection opens.
	readonly type: ConnectionType
	// Host of the endpoint; empty for the simulator.
	readonly host: string
	// TCP port of the endpoint.
	readonly port: number
	// Revision, increased by every save.
	readonly revision: number
}

// Body of PUT /api/saved-connections/:id, which creates or edits a saved connection.
export interface SavedConnectionSaveRequest {
	readonly name: string
	readonly type: ConnectionType
	readonly host: string
	readonly port: number
	// Revision the connection was edited from; 0 to create it.
	readonly revision: number
}

// Observing site saved by an operator: a named place shared by every profile.
export interface ObservingSite {
	// Id of the site.
	readonly id: string
	// Name shown to people.
	readonly name: string
	// Geodetic latitude, in degrees, north positive, [-90, 90].
	readonly latitude: number
	// Geodetic longitude, in degrees, east positive, [-180, 180].
	readonly longitude: number
	// Height above the WGS84 ellipsoid, in meters, [-500, 9000].
	readonly elevation: number
	// IANA time zone of the site's civil time ('UTC' included).
	readonly timeZone: string
	// Revision, increased by every save.
	readonly revision: number
}

// Body of PUT /api/observing-sites/:id, which creates or edits an observing site.
export interface ObservingSiteSaveRequest {
	readonly name: string
	readonly latitude: number
	readonly longitude: number
	readonly elevation: number
	readonly timeZone: string
	// Revision the site was edited from; 0 to create it.
	readonly revision: number
}

// Value kept for a preference or a camera form.
export interface WorkspaceValue {
	// Version of the shape of the value, as the web wrote it.
	readonly version: number
	// Value; null when reset to its default.
	readonly value: unknown
	// Revision, increased by every save.
	readonly revision: number
}

// Body of the PUT of a preference or a camera form.
export interface WorkspaceValueSaveRequest {
	// Version of the shape of the value.
	readonly version: number
	// Value; null resets it to its default.
	readonly value: unknown
	// Revision the value was edited from; 0 when it was never saved.
	readonly revision: number
}

// Device a role of an equipment setup takes.
export interface WorkspaceDevice {
	// Id of the device on its connection.
	readonly id: string
	// Name of the device when it was assigned.
	readonly name: string
}

// Host and port a Mount Remote Control listener was last started with.
export interface WorkspaceMountBinding {
	// Address the listener binds to.
	readonly host: string
	// TCP port of the listener.
	readonly port: number
}

// Target saved to recover a framing.
export interface WorkspaceFramingReference {
	// Id of the framing.
	readonly id: string
	// Name shown to people.
	readonly name: string
	// J2000 right ascension, in radians.
	readonly rightAscension: number
	// J2000 declination, in radians.
	readonly declination: number
	// Where the position came from.
	readonly source: 'manual' | 'sky'
	// When it was saved and last renamed, Unix milliseconds (UTC).
	readonly createdAt: number
	readonly updatedAt: number
}

// Notifications of the history a profile read or dismissed, by id; a dismissed one is also read. Body of
// PUT /api/profiles/:id/notifications, which adds to them: nothing is ever unread or listed again.
export interface WorkspaceNotificationState {
	// Notifications read.
	readonly readIds: readonly string[]
	// Notifications dismissed, hidden from the lists.
	readonly dismissedIds: readonly string[]
}

// Body of PUT /api/profiles/:id, which creates a profile or edits its name, connection, active site, or position.
export interface ProfileSaveRequest {
	readonly name: string
	// Saved connection the profile works with; null for none.
	readonly connectionId: string | null
	// Observing site the profile observes from; null for none.
	readonly activeSiteId: string | null
	// Position in the list, ascending.
	readonly sortOrder: number
	// Revision the profile was edited from; 0 to create it.
	readonly revision: number
}

// A profile and everything it keeps.
export interface ProfileRecord {
	// Id of the profile.
	readonly id: string
	// Name shown to people.
	readonly name: string
	// Saved connection the profile works with; absent when none.
	readonly connectionId?: string
	// Observing site the profile observes from; absent when none.
	readonly activeSiteId?: string
	// Position in the list, ascending.
	readonly sortOrder: number
	// Revision of the name, connection, active site, and position.
	readonly revision: number
	// When it was created, Unix milliseconds (UTC).
	readonly createdAt: number
	// Device of each role, by saved connection id, then role.
	readonly equipment: Readonly<Record<string, Readonly<Record<string, WorkspaceDevice>>>>
	// Preferences, by key.
	readonly preferences: Readonly<Partial<Record<ProfilePreferenceKey, WorkspaceValue>>>
	// Camera forms, by saved connection id, then device id, then form.
	readonly cameras: Readonly<Record<string, Readonly<Record<string, Readonly<Partial<Record<ProfileCameraForm, WorkspaceValue>>>>>>>
	// Mount Remote Control bindings, by saved connection id, then mount id, then protocol.
	readonly mountBindings: Readonly<Record<string, Readonly<Record<string, Readonly<Partial<Record<MountRemoteProtocol, WorkspaceMountBinding>>>>>>>
	// Saved framings, in the order they were saved.
	readonly framings: readonly WorkspaceFramingReference[]
	// Notifications of the retained history the profile read or dismissed, oldest first.
	readonly notifications: WorkspaceNotificationState
}

// Snapshot of the workspace: GET /api/workspace.
export interface WorkspaceSnapshot {
	// Saved connections, in list order.
	readonly connections: readonly SavedConnection[]
	// Observing sites, in list order.
	readonly sites: readonly ObservingSite[]
	// Profiles, in list order; never empty.
	readonly profiles: readonly ProfileRecord[]
}

// Notification published once a change of the workspace is committed.
export type WorkspaceEvent =
	| { readonly type: 'savedConnection:updated'; readonly connection: SavedConnection }
	| { readonly type: 'savedConnection:removed'; readonly id: string }
	| { readonly type: 'observingSite:updated'; readonly site: ObservingSite }
	| { readonly type: 'observingSite:removed'; readonly id: string }
	| { readonly type: 'profile:updated'; readonly profile: ProfileRecord }
	| { readonly type: 'profile:removed'; readonly id: string }

// Receiver of workspace events.
export type WorkspaceListener = (event: WorkspaceEvent) => void

// Outcome of a write checked against a revision: saved, refused because another revision was saved since (with the
// current one), or refused because what it belongs to does not exist.
export type WorkspaceOutcome<T> = { readonly status: 'saved'; readonly value: T } | { readonly status: 'conflict'; readonly current: T | null } | { readonly status: 'notFound' }

// Name of the profile created when the database has none.
export const DEFAULT_PROFILE_NAME = 'Default'

// Row of saved_connections.
interface ConnectionRow {
	readonly id: string
	readonly name: string
	readonly type: ConnectionType
	readonly host: string
	readonly port: number
	readonly revision: number
}

// Row of observing_sites, with its columns named as in ObservingSite.
interface SiteRow {
	readonly id: string
	readonly name: string
	readonly latitude: number
	readonly longitude: number
	readonly elevation: number
	readonly timeZone: string
	readonly revision: number
}

// Columns of observing_sites read as a SiteRow.
const SITE_COLUMNS = 'id, name, latitude, longitude, elevation, time_zone AS timeZone, revision'

// Row of profiles.
interface ProfileRow {
	readonly id: string
	readonly name: string
	readonly connection_id: string | null
	readonly active_site_id: string | null
	readonly sort_order: number
	readonly revision: number
	readonly created_at: number
}

// Row of profile_preferences and profile_camera_settings.
interface ValueRow {
	readonly version: number
	readonly value: string
	readonly revision: number
}

// Returns the value a row keeps.
function valueOf({ version, value, revision }: ValueRow): WorkspaceValue {
	return { version, value: JSON.parse(value) as unknown, revision }
}

// Returns the record at path of a nested record, creating each level missing.
function nested<T>(root: Record<string, Record<string, T>>, key: string): Record<string, T> {
	return (root[key] ??= {})
}

// Saved connections and profiles of the operators in the operational database.
export class Workspace {
	// Creates the workspace of database, publishing every committed change to listener.
	constructor(
		readonly database: AppDatabase,
		readonly listener?: WorkspaceListener,
	) {}

	// Creates the Default profile when the database has none, so a workspace always has a profile. Returns whether one
	// was created.
	ensureProfile(now: number = Date.now()): boolean {
		const { db } = this.database
		if (db.query('SELECT 1 FROM profiles LIMIT 1').get()) return false
		db.query('INSERT INTO profiles (id, name, connection_id, active_site_id, sort_order, revision, created_at, updated_at) VALUES (?, ?, NULL, NULL, 0, 1, ?, ?)').run(Bun.randomUUIDv7(), DEFAULT_PROFILE_NAME, now, now)
		return true
	}

	// Returns every saved connection, observing site, and profile.
	snapshot(): WorkspaceSnapshot {
		const { db } = this.database
		const connections = db.query<ConnectionRow, []>('SELECT id, name, type, host, port, revision FROM saved_connections ORDER BY sort_order, created_at').all()
		const sites = db.query<SiteRow, []>(`SELECT ${SITE_COLUMNS} FROM observing_sites ORDER BY sort_order, created_at`).all()
		const profiles = db.query<{ id: string }, []>('SELECT id FROM profiles ORDER BY sort_order, created_at').all()
		return { connections, sites, profiles: profiles.map(({ id }) => this.profile(id)!) }
	}

	// Returns a saved connection, or undefined.
	connection(id: string): SavedConnection | undefined {
		return this.database.db.query<ConnectionRow, [string]>('SELECT id, name, type, host, port, revision FROM saved_connections WHERE id = ?').get(id) ?? undefined
	}

	// Returns an observing site, or undefined.
	site(id: string): ObservingSite | undefined {
		return this.database.db.query<SiteRow, [string]>(`SELECT ${SITE_COLUMNS} FROM observing_sites WHERE id = ?`).get(id) ?? undefined
	}

	// Returns a profile with everything it keeps, or undefined.
	profile(id: string): ProfileRecord | undefined {
		const { db } = this.database
		const row = db.query<ProfileRow, [string]>('SELECT id, name, connection_id, active_site_id, sort_order, revision, created_at FROM profiles WHERE id = ?').get(id)
		if (!row) return undefined

		const equipment: Record<string, Record<string, WorkspaceDevice>> = {}
		for (const { saved_connection_id, role, device_id, device_name } of db.query<{ saved_connection_id: string; role: string; device_id: string; device_name: string }, [string]>('SELECT saved_connection_id, role, device_id, device_name FROM profile_equipment WHERE profile_id = ?').all(id)) {
			nested(equipment, saved_connection_id)[role] = { id: device_id, name: device_name }
		}

		const preferences: Partial<Record<ProfilePreferenceKey, WorkspaceValue>> = {}
		for (const { key, ...value } of db.query<ValueRow & { key: ProfilePreferenceKey }, [string]>('SELECT key, version, value, revision FROM profile_preferences WHERE profile_id = ?').all(id)) {
			preferences[key] = valueOf(value)
		}

		const cameras: Record<string, Record<string, Partial<Record<ProfileCameraForm, WorkspaceValue>>>> = {}
		for (const { saved_connection_id, device_id, form, ...value } of db.query<ValueRow & { saved_connection_id: string; device_id: string; form: ProfileCameraForm }, [string]>('SELECT saved_connection_id, device_id, form, version, value, revision FROM profile_camera_settings WHERE profile_id = ?').all(id)) {
			;(nested(cameras, saved_connection_id)[device_id] ??= {})[form] = valueOf(value)
		}

		const mountBindings: Record<string, Record<string, Partial<Record<MountRemoteProtocol, WorkspaceMountBinding>>>> = {}
		for (const { saved_connection_id, device_id, protocol, host, port } of db
			.query<{ saved_connection_id: string; device_id: string; protocol: MountRemoteProtocol; host: string; port: number }, [string]>('SELECT saved_connection_id, device_id, protocol, host, port FROM profile_mount_bindings WHERE profile_id = ?')
			.all(id)) {
			;(nested(mountBindings, saved_connection_id)[device_id] ??= {})[protocol] = { host, port }
		}

		const framings = db
			.query<{ id: string; name: string; right_ascension: number; declination: number; source: 'manual' | 'sky'; created_at: number; updated_at: number }, [string]>('SELECT id, name, right_ascension, declination, source, created_at, updated_at FROM framing_references WHERE profile_id = ? ORDER BY created_at, id')
			.all(id)
			.map((framing) => ({ id: framing.id, name: framing.name, rightAscension: framing.right_ascension, declination: framing.declination, source: framing.source, createdAt: framing.created_at, updatedAt: framing.updated_at }))

		const states = db.query<{ notification_id: string; dismissed: number }, [string]>('SELECT notification_id, dismissed_at IS NOT NULL AS dismissed FROM profile_notification_state JOIN notifications ON notifications.id = notification_id WHERE profile_id = ? ORDER BY sequence').all(id)
		const notifications = { readIds: states.map((state) => state.notification_id), dismissedIds: states.filter((state) => state.dismissed).map((state) => state.notification_id) }

		return {
			id,
			name: row.name,
			...(row.connection_id !== null && { connectionId: row.connection_id }),
			...(row.active_site_id !== null && { activeSiteId: row.active_site_id }),
			sortOrder: row.sort_order,
			revision: row.revision,
			createdAt: row.created_at,
			equipment,
			preferences,
			cameras,
			mountBindings,
			framings,
			notifications,
		}
	}

	// Creates a saved connection (revision 0) or edits it from revision.
	saveConnection(id: string, { name, type, host, port, revision }: SavedConnectionSaveRequest, now: number = Date.now()): WorkspaceOutcome<SavedConnection> {
		const outcome = this.database.write((): WorkspaceOutcome<SavedConnection> => {
			const current = this.connection(id)
			if ((current?.revision ?? 0) !== revision) return { status: 'conflict', current: current ?? null }

			if (current) {
				this.database.db.query('UPDATE saved_connections SET name = ?, type = ?, host = ?, port = ?, revision = ?, updated_at = ? WHERE id = ?').run(name, type, host, port, revision + 1, now, id)
			} else {
				const { next } = this.database.db.query<{ next: number }, []>('SELECT coalesce(max(sort_order) + 1, 0) AS next FROM saved_connections').get()!
				this.database.db.query('INSERT INTO saved_connections (id, name, type, host, port, sort_order, revision, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, 1, ?, ?)').run(id, name, type, host, port, next, now, now)
			}

			return { status: 'saved', value: this.connection(id)! }
		})

		if (outcome.status === 'saved') this.listener?.({ type: 'savedConnection:updated', connection: outcome.value })
		return outcome
	}

	// Deletes a saved connection, with the equipment, camera forms, and bindings of every profile on it; the profiles
	// working with it then work with none. Returns whether it existed.
	removeConnection(id: string): boolean {
		const affected = this.database.write(() => {
			const profiles = this.database.db
				.query<{ id: string }, [string, string, string, string]>(
					'SELECT id FROM profiles WHERE connection_id = ? OR id IN (SELECT profile_id FROM profile_equipment WHERE saved_connection_id = ?) OR id IN (SELECT profile_id FROM profile_camera_settings WHERE saved_connection_id = ?) OR id IN (SELECT profile_id FROM profile_mount_bindings WHERE saved_connection_id = ?)',
				)
				.all(id, id, id, id)
			const { changes } = this.database.db.query('DELETE FROM saved_connections WHERE id = ?').run(id)
			return changes > 0 ? profiles.map((profile) => profile.id) : undefined
		})

		if (!affected) return false
		this.listener?.({ type: 'savedConnection:removed', id })
		for (const profileId of affected) this.#publishProfile(profileId)
		return true
	}

	// Creates an observing site (revision 0) or edits it from revision. The profiles observing from it keep it.
	saveSite(id: string, { name, latitude, longitude, elevation, timeZone, revision }: ObservingSiteSaveRequest, now: number = Date.now()): WorkspaceOutcome<ObservingSite> {
		const outcome = this.database.write((): WorkspaceOutcome<ObservingSite> => {
			const current = this.site(id)
			if ((current?.revision ?? 0) !== revision) return { status: 'conflict', current: current ?? null }

			if (current) {
				this.database.db.query('UPDATE observing_sites SET name = ?, latitude = ?, longitude = ?, elevation = ?, time_zone = ?, revision = ?, updated_at = ? WHERE id = ?').run(name, latitude, longitude, elevation, timeZone, revision + 1, now, id)
			} else {
				const { next } = this.database.db.query<{ next: number }, []>('SELECT coalesce(max(sort_order) + 1, 0) AS next FROM observing_sites').get()!
				this.database.db.query('INSERT INTO observing_sites (id, name, latitude, longitude, elevation, time_zone, sort_order, revision, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?, 1, ?, ?)').run(id, name, latitude, longitude, elevation, timeZone, next, now, now)
			}

			return { status: 'saved', value: this.site(id)! }
		})

		if (outcome.status === 'saved') this.listener?.({ type: 'observingSite:updated', site: outcome.value })
		return outcome
	}

	// Deletes an observing site; the profiles observing from it then observe from none, and are published after the
	// site's removal. Returns whether it existed.
	removeSite(id: string): boolean {
		const affected = this.database.write(() => {
			const profiles = this.database.db.query<{ id: string }, [string]>('SELECT id FROM profiles WHERE active_site_id = ?').all(id)
			const { changes } = this.database.db.query('DELETE FROM observing_sites WHERE id = ?').run(id)
			return changes > 0 ? profiles.map((profile) => profile.id) : undefined
		})

		if (!affected) return false
		this.listener?.({ type: 'observingSite:removed', id })
		for (const profileId of affected) this.#publishProfile(profileId)
		return true
	}

	// Creates a profile (revision 0) or edits its name, connection, active site, or position from revision. notFound when
	// the connection or the site is not saved.
	saveProfile(id: string, { name, connectionId, activeSiteId, sortOrder, revision }: ProfileSaveRequest, now: number = Date.now()): WorkspaceOutcome<ProfileRecord> {
		const outcome = this.database.write((): WorkspaceOutcome<ProfileRecord> => {
			const { db } = this.database
			const current = db.query<{ revision: number }, [string]>('SELECT revision FROM profiles WHERE id = ?').get(id)
			if ((current?.revision ?? 0) !== revision) return { status: 'conflict', current: this.profile(id) ?? null }
			if (connectionId !== null && !this.connection(connectionId)) return { status: 'notFound' }
			if (activeSiteId !== null && !this.site(activeSiteId)) return { status: 'notFound' }

			if (current) db.query('UPDATE profiles SET name = ?, connection_id = ?, active_site_id = ?, sort_order = ?, revision = ?, updated_at = ? WHERE id = ?').run(name, connectionId, activeSiteId, sortOrder, revision + 1, now, id)
			else db.query('INSERT INTO profiles (id, name, connection_id, active_site_id, sort_order, revision, created_at, updated_at) VALUES (?, ?, ?, ?, ?, 1, ?, ?)').run(id, name, connectionId, activeSiteId, sortOrder, now, now)

			return { status: 'saved', value: this.profile(id)! }
		})

		if (outcome.status === 'saved') this.listener?.({ type: 'profile:updated', profile: outcome.value })
		return outcome
	}

	// Deletes a profile with everything it keeps, never the last one. Returns removed, lastProfile, or notFound.
	removeProfile(id: string): 'removed' | 'lastProfile' | 'notFound' {
		const outcome = this.database.write(() => {
			const { db } = this.database
			if (!db.query('SELECT 1 FROM profiles WHERE id = ?').get(id)) return 'notFound'
			if (db.query<{ count: number }, []>('SELECT count(*) AS count FROM profiles').get()!.count <= 1) return 'lastProfile'
			db.query('DELETE FROM profiles WHERE id = ?').run(id)
			return 'removed'
		})

		if (outcome === 'removed') this.listener?.({ type: 'profile:removed', id })
		return outcome
	}

	// Replaces the equipment setup of a profile on a saved connection; a role absent from setup takes no device. The
	// last write wins. Returns false when the profile or the connection does not exist.
	saveEquipment(profileId: string, connectionId: string, setup: Readonly<Record<string, WorkspaceDevice>>): boolean {
		const saved = this.database.write(() => {
			if (!this.#exists(profileId, connectionId)) return false
			const { db } = this.database
			db.query('DELETE FROM profile_equipment WHERE profile_id = ? AND saved_connection_id = ?').run(profileId, connectionId)
			const insert = db.query('INSERT INTO profile_equipment (profile_id, saved_connection_id, role, device_id, device_name) VALUES (?, ?, ?, ?, ?)')
			for (const [role, device] of Object.entries(setup)) insert.run(profileId, connectionId, role, device.id, device.name)
			return true
		})

		if (saved) this.#publishProfile(profileId)
		return saved
	}

	// Saves a preference of a profile edited from revision.
	savePreference(profileId: string, key: ProfilePreferenceKey, request: WorkspaceValueSaveRequest, now: number = Date.now()): WorkspaceOutcome<WorkspaceValue> {
		return this.#saveValue(profileId, undefined, request, {
			select: () => this.database.db.query<ValueRow, [string, string]>('SELECT version, value, revision FROM profile_preferences WHERE profile_id = ? AND key = ?').get(profileId, key),
			upsert: (version, value, revision) =>
				this.database.db
					.query('INSERT INTO profile_preferences (profile_id, key, version, value, revision, updated_at) VALUES (?, ?, ?, ?, ?, ?) ON CONFLICT (profile_id, key) DO UPDATE SET version = excluded.version, value = excluded.value, revision = excluded.revision, updated_at = excluded.updated_at')
					.run(profileId, key, version, value, revision, now),
		})
	}

	// Saves a form of a camera of a profile edited from revision.
	saveCameraForm(profileId: string, connectionId: string, deviceId: string, form: ProfileCameraForm, request: WorkspaceValueSaveRequest, now: number = Date.now()): WorkspaceOutcome<WorkspaceValue> {
		return this.#saveValue(profileId, connectionId, request, {
			select: () => this.database.db.query<ValueRow, [string, string, string, string]>('SELECT version, value, revision FROM profile_camera_settings WHERE profile_id = ? AND saved_connection_id = ? AND device_id = ? AND form = ?').get(profileId, connectionId, deviceId, form),
			upsert: (version, value, revision) =>
				this.database.db
					.query(
						'INSERT INTO profile_camera_settings (profile_id, saved_connection_id, device_id, form, version, value, revision, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?) ON CONFLICT (profile_id, saved_connection_id, device_id, form) DO UPDATE SET version = excluded.version, value = excluded.value, revision = excluded.revision, updated_at = excluded.updated_at',
					)
					.run(profileId, connectionId, deviceId, form, version, value, revision, now),
		})
	}

	// Saves the Mount Remote Control binding of a protocol of a mount in a profile. The last write wins. Returns false
	// when the profile or the connection does not exist.
	saveMountBinding(profileId: string, connectionId: string, deviceId: string, protocol: MountRemoteProtocol, { host, port }: WorkspaceMountBinding): boolean {
		const saved = this.database.write(() => {
			if (!this.#exists(profileId, connectionId)) return false
			this.database.db
				.query('INSERT INTO profile_mount_bindings (profile_id, saved_connection_id, device_id, protocol, host, port) VALUES (?, ?, ?, ?, ?, ?) ON CONFLICT (profile_id, saved_connection_id, device_id, protocol) DO UPDATE SET host = excluded.host, port = excluded.port')
				.run(profileId, connectionId, deviceId, protocol, host, port)
			return true
		})

		if (saved) this.#publishProfile(profileId)
		return saved
	}

	// Saves a framing of a profile, creating it or replacing its name and position. The last write wins. Returns false
	// when the profile does not exist.
	saveFramingReference(profileId: string, framing: WorkspaceFramingReference): boolean {
		const saved = this.database.write(() => {
			if (!this.#exists(profileId)) return false
			this.database.db
				.query(
					'INSERT INTO framing_references (id, profile_id, name, right_ascension, declination, source, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?) ON CONFLICT (id) DO UPDATE SET name = excluded.name, right_ascension = excluded.right_ascension, declination = excluded.declination, source = excluded.source, updated_at = excluded.updated_at WHERE profile_id = excluded.profile_id',
				)
				.run(framing.id, profileId, framing.name, framing.rightAscension, framing.declination, framing.source, framing.createdAt, framing.updatedAt)
			return true
		})

		if (saved) this.#publishProfile(profileId)
		return saved
	}

	// Deletes a framing of a profile. Returns whether it existed.
	removeFramingReference(profileId: string, framingId: string): boolean {
		const { changes } = this.database.db.query('DELETE FROM framing_references WHERE id = ? AND profile_id = ?').run(framingId, profileId)
		if (changes > 0) this.#publishProfile(profileId)
		return changes > 0
	}

	// Marks notifications as read and dismissed in a profile, adding to what it read and dismissed before; ids of
	// notifications the history no longer retains are ignored. Returns false when the profile does not exist.
	saveNotificationState(profileId: string, { readIds, dismissedIds }: WorkspaceNotificationState, now: number = Date.now()): boolean {
		const saved = this.database.write(() => {
			if (!this.#exists(profileId)) return false
			const { db } = this.database
			const read = db.query('INSERT INTO profile_notification_state (profile_id, notification_id, read_at) SELECT ?, id, ? FROM notifications WHERE id = ? ON CONFLICT DO NOTHING')
			const dismissed = db.query('INSERT INTO profile_notification_state (profile_id, notification_id, read_at, dismissed_at) SELECT ?, id, ?, ? FROM notifications WHERE id = ? ON CONFLICT DO UPDATE SET dismissed_at = coalesce(dismissed_at, excluded.dismissed_at)')
			for (const id of readIds) read.run(profileId, now, id)
			for (const id of dismissedIds) dismissed.run(profileId, now, now, id)
			return true
		})

		if (saved) this.#publishProfile(profileId)
		return saved
	}

	// Whether a profile exists, and the saved connection when given.
	#exists(profileId: string, connectionId?: string) {
		const { db } = this.database
		return !!db.query('SELECT 1 FROM profiles WHERE id = ?').get(profileId) && (connectionId === undefined || !!this.connection(connectionId))
	}

	// Saves a value of a profile edited from revision, through the select and upsert of its table.
	#saveValue(profileId: string, connectionId: string | undefined, { version, value, revision }: WorkspaceValueSaveRequest, table: { readonly select: () => ValueRow | null; readonly upsert: (version: number, value: string, revision: number) => unknown }): WorkspaceOutcome<WorkspaceValue> {
		const outcome = this.database.write((): WorkspaceOutcome<WorkspaceValue> => {
			if (!this.#exists(profileId, connectionId)) return { status: 'notFound' }
			const current = table.select()
			if ((current?.revision ?? 0) !== revision) return { status: 'conflict', current: current ? valueOf(current) : null }
			table.upsert(version, JSON.stringify(value ?? null), revision + 1)
			return { status: 'saved', value: valueOf(table.select()!) }
		})

		if (outcome.status === 'saved') this.#publishProfile(profileId)
		return outcome
	}

	// Publishes the current record of a profile, if it still exists.
	#publishProfile(id: string) {
		const profile = this.profile(id)
		if (profile) this.listener?.({ type: 'profile:updated', profile })
	}
}

// Responds to a write checked against a revision: 200 with the saved value, 409 conflict with the current one under
// field, or 404.
function outcomeResponse<T>(outcome: WorkspaceOutcome<T>, field: string): Response {
	if (outcome.status === 'saved') return Response.json(outcome.value)
	if (outcome.status === 'conflict') return errorResponse('It was changed by another tab', 409, 'conflict', { [field]: outcome.current })
	return errorResponse('Profile, saved connection, or observing site not found', 404, 'notFound')
}

// Responds 204 when a write applied, 404 otherwise.
function savedResponse(saved: boolean): Response {
	return saved ? new Response(undefined, { status: 204 }) : errorResponse('Profile or saved connection not found', 404, 'notFound')
}

// Creates the routes of the workspace under /api/workspace, /api/saved-connections, /api/observing-sites, and
// /api/profiles.
export function createWorkspaceRoutes(workspace: Workspace) {
	return {
		'/api/workspace': {
			// Every saved connection, observing site, and profile.
			GET: () => Response.json(workspace.snapshot()),
		},
		'/api/saved-connections/:id': {
			// Creates or edits a saved connection (SavedConnectionSaveRequest); 409 with the current one when another
			// revision was saved since.
			PUT: async (req) => outcomeResponse(workspace.saveConnection(req.params.id, (await req.json()) as SavedConnectionSaveRequest), 'connection'),
			// Deletes a saved connection and what every profile keeps on it; 204 whether or not it existed.
			DELETE: (req) => {
				workspace.removeConnection(req.params.id)
				return new Response(undefined, { status: 204 })
			},
		},
		'/api/observing-sites/:id': {
			// Creates or edits an observing site (ObservingSiteSaveRequest); 409 with the current one when another revision
			// was saved since.
			PUT: async (req) => outcomeResponse(workspace.saveSite(req.params.id, (await req.json()) as ObservingSiteSaveRequest), 'site'),
			// Deletes an observing site, clearing it from every profile observing from it; 204 whether or not it existed.
			DELETE: (req) => {
				workspace.removeSite(req.params.id)
				return new Response(undefined, { status: 204 })
			},
		},
		'/api/profiles/:id': {
			// Creates or edits a profile (ProfileSaveRequest); 409 with the current one when another revision was saved
			// since, 404 when the connection or the site is not saved.
			PUT: async (req) => outcomeResponse(workspace.saveProfile(req.params.id, (await req.json()) as ProfileSaveRequest), 'profile'),
			// Deletes a profile; 409 lastProfile for the last one, 204 when it did not exist.
			DELETE: (req) => {
				const outcome = workspace.removeProfile(req.params.id)
				return outcome === 'lastProfile' ? errorResponse('The last profile cannot be deleted', 409, 'lastProfile') : new Response(undefined, { status: 204 })
			},
		},
		'/api/profiles/:id/equipment/:connectionId': {
			// Replaces the equipment setup of a profile on a saved connection ({ setup }); 404 for an unknown one.
			PUT: async (req) => savedResponse(workspace.saveEquipment(req.params.id, req.params.connectionId, ((await req.json()) as { setup: Record<string, WorkspaceDevice> }).setup)),
		},
		'/api/profiles/:id/preferences/:key': {
			// Saves a preference (WorkspaceValueSaveRequest); 409 with the current value, 404 for an unknown profile.
			PUT: async (req) => outcomeResponse(workspace.savePreference(req.params.id, req.params.key as ProfilePreferenceKey, (await req.json()) as WorkspaceValueSaveRequest), 'value'),
		},
		'/api/profiles/:id/cameras/:connectionId/:deviceId/:form': {
			// Saves a form of a camera (WorkspaceValueSaveRequest); 409 with the current value, 404 for an unknown profile or connection.
			PUT: async (req) => {
				const { id, connectionId, deviceId, form } = req.params
				return outcomeResponse(workspace.saveCameraForm(id, connectionId, deviceId, form as ProfileCameraForm, (await req.json()) as WorkspaceValueSaveRequest), 'value')
			},
		},
		'/api/profiles/:id/mount-bindings/:connectionId/:deviceId/:protocol': {
			// Saves a Mount Remote Control binding (WorkspaceMountBinding); 404 for an unknown profile or connection.
			PUT: async (req) => {
				const { id, connectionId, deviceId, protocol } = req.params
				return savedResponse(workspace.saveMountBinding(id, connectionId, deviceId, protocol as MountRemoteProtocol, (await req.json()) as WorkspaceMountBinding))
			},
		},
		'/api/profiles/:id/notifications': {
			// Marks notifications as read and dismissed in a profile (WorkspaceNotificationState); 404 for an unknown profile.
			PUT: async (req) => savedResponse(workspace.saveNotificationState(req.params.id, (await req.json()) as WorkspaceNotificationState)),
		},
		'/api/profiles/:id/framing-references/:framingId': {
			// Saves a framing (WorkspaceFramingReference without its id); 404 for an unknown profile.
			PUT: async (req) => {
				const { id, framingId } = req.params
				return savedResponse(workspace.saveFramingReference(id, { ...((await req.json()) as Omit<WorkspaceFramingReference, 'id'>), id: framingId }))
			},
			// Deletes a framing; 204 whether or not it existed.
			DELETE: (req) => {
				workspace.removeFramingReference(req.params.id, req.params.framingId)
				return new Response(undefined, { status: 204 })
			},
		},
	} as const satisfies Bun.Serve.Routes<undefined, string>
}
