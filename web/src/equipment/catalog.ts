import type { CameraBinding, CameraBindingsSnapshot, CameraSensor, CatalogCameraFields, CatalogCameraSensor, ServerEvent } from 'api'
import { nanoid } from 'nanoid'
import { proxy } from 'valtio'
import { type ApiFetch, browserFetch, jsonInit, responseError } from '../http'
import { SnapshotRefreshes } from '../refresh'

// Equipment Catalog of the tab: the physical cameras calibration frames and masters are recorded against, one catalog
// shared by every profile, tab, and browser, which the server keeps as part of the workspace (sync.ts of the profiles
// writes what the tab changes), and the binding of each camera device to one of them, which belongs to the physical
// device, holds for every profile, and is mirrored from the server (GET /api/equipment-catalog/bindings and
// catalogCamera:bindingChanged). Binding a device never commands it; the wizards, the captures, and the calibrators read
// the binding on the server.

// Camera of the Equipment Catalog as the tab holds it; the synchronization keeps its revision.
export interface CatalogCamera extends CatalogCameraFields {
	// Id of the camera, generated by the tab that created it.
	readonly id: string
}

// Cameras of the catalog of the tab.
export interface CatalogState {
	// Cameras, in list order.
	cameras: CatalogCamera[]
}

// Catalog of the tab, filled from the workspace.
export const catalogState = proxy<CatalogState>({ cameras: [] })

// Mirror of the bindings of the server.
export interface CameraBindingsState {
	// Binding of each camera device, by bindingKey.
	bindings: Record<string, CameraBinding>
	// Whether the bindings were read at least once.
	loaded: boolean
}

// Bindings of the tab.
export const cameraBindingsState = proxy<CameraBindingsState>({ bindings: {}, loaded: false })

// Ordering of the refreshes of the bindings against their events.
const refreshes = new SnapshotRefreshes()

// Camera device of an open connection, as a binding names it.
export interface BindableDevice {
	// Id of the open connection that provides it.
	readonly connectionId: string
	// Exact id of the device.
	readonly id: string
}

// Outcome of a save of a camera of the catalog: saved, or refused for an empty or taken name, or a sensor out of range.
export type CatalogCameraSave = { readonly ok: true; readonly camera: CatalogCamera } | { readonly ok: false; readonly reason: 'name' | 'nameTaken' | 'sensor' }

// Returns the key of the binding of a device.
export function bindingKey(connectionId: string, deviceId: string) {
	return `${connectionId}/${deviceId}`
}

// Returns the text of an optional field trimmed, or undefined when it is blank.
function optionalText(text: string | undefined) {
	const trimmed = text?.trim()
	return trimmed ? trimmed : undefined
}

// Whether a declared sensor holds a positive whole size, and a positive pixel size and bit depth when given.
function validSensor({ width, height, pixelSize, bits }: CatalogCameraSensor) {
	return Number.isInteger(width) && width > 0 && Number.isInteger(height) && height > 0 && (pixelSize === undefined || (Number.isFinite(pixelSize) && pixelSize > 0)) && (bits === undefined || (Number.isInteger(bits) && bits > 0 && bits <= 32))
}

// Creates a camera of the catalog, or replaces the one of id, with its name and optional fields trimmed. Refused when the
// name is blank or another camera has it without regard to case, or the sensor is out of range.
export function saveCatalogCamera(state: CatalogState, input: CatalogCameraFields, id?: string): CatalogCameraSave {
	const name = input.name.trim()
	if (!name) return { ok: false, reason: 'name' }
	if (state.cameras.some((camera) => camera.id !== id && camera.name.toLowerCase() === name.toLowerCase())) return { ok: false, reason: 'nameTaken' }
	if (input.sensor && !validSensor(input.sensor)) return { ok: false, reason: 'sensor' }

	const model = optionalText(input.model)
	const serial = optionalText(input.serial)
	const notes = optionalText(input.notes)
	const cfa = optionalText(input.sensor?.cfa)
	const sensor = input.sensor && { width: input.sensor.width, height: input.sensor.height, ...(input.sensor.pixelSize !== undefined && { pixelSize: input.sensor.pixelSize }), ...(cfa && { cfa: cfa.toUpperCase() }), ...(input.sensor.bits !== undefined && { bits: input.sensor.bits }) }
	const index = state.cameras.findIndex((camera) => camera.id === id)
	const camera: CatalogCamera = { id: index >= 0 && id ? id : nanoid(), name, ...(model && { model }), ...(serial && { serial }), ...(notes && { notes }), ...(sensor && { sensor }), archived: input.archived }
	if (index >= 0) state.cameras[index] = camera
	else state.cameras.push(camera)
	return { ok: true, camera }
}

// Creates a camera of the catalog on the server at once, rather than through the synchronization of the workspace, for a
// binding that must name it right after; the server publishes it, and the synchronization adds it to the tab. Returns the
// camera, or the error message of a refusal.
export async function createCatalogCamera(fields: CatalogCameraFields, request: ApiFetch = browserFetch): Promise<{ readonly camera: CatalogCamera } | { readonly error: string }> {
	try {
		const response = await request(`/api/catalog-cameras/${encodeURIComponent(nanoid())}`, jsonInit('PUT', { ...fields, revision: 0 }))
		if (!response.ok) return { error: await responseError(response) }
		const { revision: _, ...camera } = (await response.json()) as CatalogCamera & { readonly revision: number }
		return { camera }
	} catch (error) {
		return { error: error instanceof Error ? error.message : String(error) }
	}
}

// Removes a camera from the catalog; the server refuses it while calibration frames or masters are recorded against it.
export function removeCatalogCamera(state: CatalogState, id: string) {
	state.cameras = state.cameras.filter((camera) => camera.id !== id)
}

// Returns the name of a camera of the catalog, or a placeholder for one the catalog does not hold.
export function catalogCameraName(cameras: readonly Pick<CatalogCamera, 'id' | 'name'>[], id: string | undefined) {
	return cameras.find((camera) => camera.id === id)?.name ?? (id === undefined ? 'No camera' : 'Unknown camera')
}

// Returns the camera of the catalog a device is bound to, or undefined.
export function boundCameraId(state: Pick<CameraBindingsState, 'bindings'>, device: BindableDevice | undefined) {
	return device && state.bindings[bindingKey(device.connectionId, device.id)]?.cameraId
}

// Returns the camera a device of an endpoint that changed most likely is: the one camera of the catalog, not archived,
// that a binding of a device of the same driver name names, or undefined when there is none or more than one.
export function suggestedCameraId(state: Pick<CameraBindingsState, 'bindings'>, cameras: readonly Pick<CatalogCamera, 'id' | 'archived'>[], deviceName: string) {
	const usable = new Set(cameras.filter((camera) => !camera.archived).map((camera) => camera.id))
	const named = new Set(Object.values(state.bindings).flatMap((binding) => (binding.deviceName === deviceName && usable.has(binding.cameraId) ? [binding.cameraId] : [])))
	return named.size === 1 ? [...named][0] : undefined
}

// Returns the fields of a connected camera device worth copying into the catalog: its driver name as the model, and the
// unbinned sensor it reports (pixels, micrometers), when it reports one.
export function deviceFields(device: { readonly name: string }, sensor: CameraSensor | undefined): Pick<CatalogCameraFields, 'model' | 'sensor'> {
	return { model: device.name, ...(sensor && { sensor: { width: sensor.width, height: sensor.height, pixelSize: sensor.pixelSize } }) }
}

// Returns why a camera of the catalog does not look like the device bound to it, from the sensors both declare, or
// undefined when they agree or either is unknown. Only a warning: the binding is the operator's.
export function sensorMismatch(camera: Pick<CatalogCamera, 'sensor'> | undefined, sensor: CameraSensor | undefined) {
	if (!camera?.sensor || !sensor) return undefined
	if (camera.sensor.width !== sensor.width || camera.sensor.height !== sensor.height) return `The camera of the catalog declares a ${camera.sensor.width} × ${camera.sensor.height} sensor, and the device reports ${sensor.width} × ${sensor.height}`
	if (camera.sensor.pixelSize !== undefined && Math.abs(camera.sensor.pixelSize - sensor.pixelSize) > 0.01) return `The camera of the catalog declares ${camera.sensor.pixelSize} µm pixels, and the device reports ${sensor.pixelSize} µm`
	return undefined
}

// Fetches the bindings of the server, leaving the devices whose binding changed by an event meanwhile as the event set
// them. Returns whether they were read.
export async function refreshCameraBindings(state: CameraBindingsState, request: ApiFetch = browserFetch) {
	const token = refreshes.start()

	try {
		const response = await request('/api/equipment-catalog/bindings')
		if (!response.ok || !refreshes.current(token)) return false
		const { bindings } = (await response.json()) as CameraBindingsSnapshot
		if (!refreshes.current(token)) return false
		state.bindings = refreshes.merge(state.bindings, bindings, (binding) => bindingKey(binding.connectionId, binding.deviceId))
		state.loaded = true
		return true
	} catch {
		return false
	} finally {
		refreshes.end(token)
	}
}

// Applies a change of a binding the server published.
export function handleCameraBindingsEvent(state: CameraBindingsState, event: ServerEvent) {
	if (event.type !== 'catalogCamera:bindingChanged') return
	const key = bindingKey(event.connectionId, event.deviceId)
	refreshes.updated(key)
	if (event.binding) state.bindings[key] = event.binding
	else delete state.bindings[key]
}

// Binds a camera device to a camera of the catalog, or unbinds it when cameraId is undefined. The server publishes the
// change; the answer is applied too, so the tab never waits for the event. Returns the error message of a refusal.
export async function bindCamera(state: CameraBindingsState, device: BindableDevice, cameraId: string | undefined, request: ApiFetch = browserFetch): Promise<string | undefined> {
	try {
		const response = await request('/api/equipment-catalog/bindings', jsonInit('PUT', { connectionId: device.connectionId, deviceId: device.id, cameraId: cameraId ?? null }))
		if (!response.ok) return await responseError(response)
		const { binding } = (await response.json()) as { readonly binding?: CameraBinding }
		const key = bindingKey(device.connectionId, device.id)
		if (binding) state.bindings[key] = binding
		else delete state.bindings[key]
		return undefined
	} catch (error) {
		return error instanceof Error ? error.message : String(error)
	}
}
