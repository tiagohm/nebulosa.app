import type { Client, Device } from 'nebulosa/src/devices/indi/device'
import type { FailedOperationResult, OperationFailureReason, OperationResult } from 'nebulosa/src/devices/orchestration/operation'
import { resourceKey } from 'nebulosa/src/devices/orchestration/resource'
import type { DeviceRegistry, ManagedDeviceMap, ManagedDeviceType } from './devices'
import type { OperationKind, OperationRegistry } from './operations'

// HTTP contract shared by the device command services. A command addresses one device of one open
// connection by its exact id and answers in one of two ways:
// - an immediate command (a setting the driver applies at once) is awaited and answered 204, or with the
//   error that refused or failed it;
// - a durable command (a motion or anything else the device takes time to complete) is answered 202 with
//   the id of the operation running it as soon as it started; its outcome is published later as
//   operation:updated events from the real operation result, never assumed from the request.
// Every durable request carries a token the tab generates for it, so a repeated request answers the
// operation of the first one instead of commanding the device again. Every error is { error, code }, with
// a code from a fixed set the client can rely on and a message meant for people.

// Stable code of a refused or failed command:
// - notFound: the connection is not open or has no such device.
// - disconnected: the device is not connected to its hardware.
// - busy: another operation holds the device, or it is moving on its own.
// - unsupported: the device lacks the capability, or its state forbids the command (parked, slaved).
// - invalidParameter: a parameter is outside what the device accepts.
// - timeout: the device did not reach the commanded state in time.
// - rejected: the command was canceled before completing.
// - deviceError: the driver reported an error.
// - connectionLost: the device disappeared while commanded.
// - unknownResult: the command could not be confirmed as sent; the device may or may not have received it.
// - serviceUnavailable: a service the command depends on, such as an ephemeris provider, failed or is absent.
export type CommandErrorCode = 'notFound' | 'disconnected' | 'busy' | 'unsupported' | 'invalidParameter' | 'timeout' | 'rejected' | 'deviceError' | 'connectionLost' | 'unknownResult' | 'serviceUnavailable'

// Body of an error response.
export interface CommandError {
	// Message meant for people.
	readonly error: string
	// Stable code of the error.
	readonly code: CommandErrorCode
}

// Body of every durable command request: the identity of the request.
export interface CommandRequest {
	// Identity of this request, generated by the tab and unique per user action.
	readonly token: string
}

// Response of an accepted durable command.
export interface CommandAccepted {
	// Id of the operation running the command, repeated by its operation:updated events.
	readonly operationId: string
}

// Resolves an open connection id to its client; undefined when the connection is not open.
export type ClientResolver = (connectionId: string) => Client | undefined

// Status and code each operation failure reason is answered with.
const FAILURES: Readonly<Record<OperationFailureReason, readonly [number, CommandErrorCode]>> = {
	busy: [409, 'busy'],
	aborted: [409, 'rejected'],
	disconnected: [409, 'disconnected'],
	removed: [409, 'connectionLost'],
	timeout: [504, 'timeout'],
	alert: [502, 'deviceError'],
	commandFailed: [502, 'unknownResult'],
	unexpectedState: [422, 'unsupported'],
}

// Responds with an error message, a status, and a stable code.
export function errorResponse(message: string, status: number, code: CommandErrorCode): Response {
	return Response.json({ error: message, code } satisfies CommandError, { status })
}

// Returns the stable code of an operation failure reason.
export function failureCode(reason: OperationFailureReason): CommandErrorCode {
	return FAILURES[reason][1]
}

// Responds with the error of a failed operation; action names the command for the fallback message.
export function failureResponse({ reason, error }: FailedOperationResult, action: string): Response {
	const [status, code] = FAILURES[reason]
	return errorResponse(reason === 'busy' ? 'The device is busy' : (error ?? `${action} failed (${reason})`), status, code)
}

// Responds 404 for a device the connection does not provide.
export function notFound(what: string): Response {
	return errorResponse(`${what} not found`, 404, 'notFound')
}

// Responds 409 for a device that is not connected to its hardware.
export function disconnected(what: string): Response {
	return errorResponse(`The ${what.toLowerCase()} is disconnected`, 409, 'disconnected')
}

// Responds 422 for a command the device cannot run.
export function unsupported(message: string): Response {
	return errorResponse(message, 422, 'unsupported')
}

// Responds 409 for a device another operation holds or that is moving on its own.
export function busy(): Response {
	return errorResponse('The device is busy', 409, 'busy')
}

// Awaits an immediate command and responds 204 when it succeeded, or with its error.
export async function settle(result: Promise<OperationResult<unknown>>, action: string): Promise<Response> {
	const outcome = await result
	return outcome.ok ? new Response(null, { status: 204 }) : failureResponse(outcome, action)
}

// Resolves the device of a managed type with exactly this id on an open connection.
export function findDevice<T extends ManagedDeviceType>(devices: DeviceRegistry, client: ClientResolver, connectionId: string, type: T, deviceId: string): ManagedDeviceMap[T] | undefined {
	const owner = client(connectionId)
	return owner && devices.device(owner, type, deviceId)
}

// Resolves the connected device of a managed type with exactly this id on an open connection, or the
// response refusing it: 404 when there is none, 409 when it is disconnected. what names the device in the
// messages, such as "Focuser".
export function connectedDevice<T extends ManagedDeviceType>(devices: DeviceRegistry, client: ClientResolver, connectionId: string, type: T, deviceId: string, what: string): ManagedDeviceMap[T] | Response {
	const device = findDevice(devices, client, connectionId, type, deviceId)
	if (!device) return notFound(what)
	if (!device.connected) return disconnected(what)
	return device
}

// Responds with the control state of a device of a managed type, or 404 when the connection is not open
// or has no such device.
export function stateResponse(devices: DeviceRegistry, client: ClientResolver, connectionId: string, type: ManagedDeviceType, deviceId: string, what: string): Response {
	const owner = client(connectionId)
	const state = owner && devices.state(owner, type, deviceId)
	return state ? Response.json(state) : notFound(what)
}

// Stops the motion of a device: cancels the operation holding the physical device, so its cleanup cannot
// command the motion again, then sends the stop, which never needs the device to be granted. Responds 204
// once the device reports a standstill, and 409 when the stop could not be confirmed.
export async function stopResponse(operations: OperationRegistry, device: Device, stop: () => Promise<OperationResult<unknown>>): Promise<Response> {
	await operations.coordinator.cancelByDevice(resourceKey(device))
	const result = await stop()
	return result.ok ? new Response(null, { status: 204 }) : errorResponse(result.error ?? `The device did not stop (${result.reason})`, 409, failureCode(result.reason))
}

// Starts a durable command on a device and responds 202 with its operation id. A token already seen
// answers its first operation without commanding again; otherwise a device that cannot be granted now is
// refused as busy before anything is sent.
export function startCommand(operations: OperationRegistry, kind: OperationKind, connectionId: string, device: Device, { token }: CommandRequest, start: () => Promise<OperationResult<unknown>>): Response {
	const known = operations.started(token)
	if (known) return Response.json({ operationId: known.operationId } satisfies CommandAccepted, { status: 202 })
	if (!operations.available(device)) return busy()

	const { operationId } = operations.run(kind, [{ connectionId, deviceId: device.id }], token, start)
	return Response.json({ operationId } satisfies CommandAccepted, { status: 202 })
}
