import type { AppDatabase } from './database'
import type { ObservingConstraints, ObservingMode, ObservingTargetRef, PlanningBodyCode, PlanningSite } from './observingplanner.astronomy'

// Night plans of the Observing Planner in the operational database (observing_plans and observing_plan_items): what the
// operator chose, never anything computed from it. A plan and its items are one document with one revision; every save
// writes the whole document in one transaction, so a reorder or an edit is never half applied, and an outdated
// revision is refused. Times are Unix milliseconds (UTC) and angles radians.

// Constraints of an item replacing those of its plan; an absent field keeps the plan's.
export type ObservingConstraintsOverride = Partial<Omit<ObservingConstraints, 'mode'>>

// Item of a night plan.
export interface ObservingPlanItem {
	// Id within the plan, generated by the tab that added it.
	readonly id: string
	// Target.
	readonly target: ObservingTargetRef
	// Name of the target when it was added; the name of coordinates.
	readonly targetName: string
	// Priority, 1 (lowest) to 5 (highest); it never reorders or schedules anything.
	readonly priority: number
	// Continuous time requested, in milliseconds.
	readonly requestedDurationMs: number
	// Start the operator chose; absent while unscheduled.
	readonly scheduledStartAt?: number
	// Constraints replacing those of the plan; absent keeps the plan's.
	readonly constraints?: ObservingConstraintsOverride
	// Notes of the operator.
	readonly notes: string
}

// Content of a night plan, as the operator edits it.
export interface ObservingPlanDocument {
	// Name shown to people.
	readonly name: string
	// Civil date of the evening in the site's zone, YYYY-MM-DD.
	readonly eveningDate: string
	// Saved site the place was copied from; a link to its origin only.
	readonly observingSiteId?: string
	// Copy of the site.
	readonly site: PlanningSite
	// Base constraints of the items.
	readonly constraints: ObservingConstraints
	// Items, in the operator's order.
	readonly items: readonly ObservingPlanItem[]
}

// Saved night plan.
export interface ObservingPlan extends ObservingPlanDocument {
	// Id of the plan.
	readonly id: string
	// Revision, increased by every save; >= 1.
	readonly revision: number
	// When it was created.
	readonly createdAt: number
	// When it was last changed.
	readonly updatedAt: number
}

// Body of PUT /api/observing-planner/plans/:id: the whole document and the revision it was edited from (0 creates it).
export interface ObservingPlanSaveRequest extends ObservingPlanDocument {
	// Revision the tab last saw; 0 for a new plan.
	readonly revision: number
}

// Outcome of a write: saved, refused because another revision was saved since (with the current plan, null when it no
// longer exists), or refused because the plan does not exist.
export type ObservingPlanOutcome = { readonly status: 'saved'; readonly plan: ObservingPlan } | { readonly status: 'conflict'; readonly current: ObservingPlan | null } | { readonly status: 'notFound' }

// Outcome of a removal.
export type ObservingPlanRemoval = { readonly status: 'removed' } | { readonly status: 'conflict'; readonly current: ObservingPlan } | { readonly status: 'notFound' }

// Row of a plan.
interface PlanRow {
	readonly id: string
	readonly name: string
	readonly eveningDate: string
	readonly observingSiteId: string | null
	readonly siteName: string
	readonly latitude: number
	readonly longitude: number
	readonly elevation: number
	readonly timeZone: string
	readonly mode: ObservingMode
	readonly minimumAltitude: number
	readonly maximumAirmass: number | null
	readonly maximumSunAltitude: number
	readonly minimumMoonSeparation: number | null
	readonly minimumContinuousMs: number
	readonly revision: number
	readonly createdAt: number
	readonly updatedAt: number
}

// Row of an item.
interface ItemRow {
	readonly planId: string
	readonly id: string
	readonly targetKind: ObservingTargetRef['kind']
	readonly catalogId: number | null
	readonly bodyCode: PlanningBodyCode | null
	readonly rightAscension: number | null
	readonly declination: number | null
	readonly targetName: string
	readonly priority: number
	readonly requestedDurationMs: number
	readonly scheduledStartAt: number | null
	readonly minimumAltitude: number | null
	readonly maximumAirmass: number | null
	readonly maximumSunAltitude: number | null
	readonly minimumMoonSeparation: number | null
	readonly minimumContinuousMs: number | null
	readonly notes: string
}

// Columns of a plan, named as the API names them.
const PLAN_COLUMNS =
	'id, name, evening_date AS eveningDate, observing_site_id AS observingSiteId, site_name AS siteName, latitude, longitude, elevation, time_zone AS timeZone, mode, minimum_altitude AS minimumAltitude, maximum_airmass AS maximumAirmass, maximum_sun_altitude AS maximumSunAltitude, minimum_moon_separation AS minimumMoonSeparation, minimum_continuous_ms AS minimumContinuousMs, revision, created_at AS createdAt, updated_at AS updatedAt'

// Columns of an item, named as the API names them.
const ITEM_COLUMNS =
	'plan_id AS planId, id, target_kind AS targetKind, catalog_id AS catalogId, body_code AS bodyCode, right_ascension AS rightAscension, declination, target_name AS targetName, priority, requested_duration_ms AS requestedDurationMs, scheduled_start_at AS scheduledStartAt, minimum_altitude AS minimumAltitude, maximum_airmass AS maximumAirmass, maximum_sun_altitude AS maximumSunAltitude, minimum_moon_separation AS minimumMoonSeparation, minimum_continuous_ms AS minimumContinuousMs, notes'

// Copies the defined fields of an object, so absent optional fields stay absent rather than undefined or null.
function defined<T extends object>(value: { [K in keyof T]: T[K] | null | undefined }): T {
	const result: Partial<T> = {}
	for (const key of Object.keys(value) as (keyof T)[]) if (value[key] !== null && value[key] !== undefined) result[key] = value[key]
	return result as T
}

// Returns the target of an item row.
function targetOf(row: ItemRow): ObservingTargetRef {
	if (row.targetKind === 'catalog') return { kind: 'catalog', id: row.catalogId! }
	if (row.targetKind === 'body') return { kind: 'body', code: row.bodyCode! }
	return { kind: 'coordinates', name: row.targetName, rightAscension: row.rightAscension!, declination: row.declination! }
}

// Returns the item of a row.
function itemOf(row: ItemRow): ObservingPlanItem {
	const constraints = defined<ObservingConstraintsOverride>({ minimumAltitude: row.minimumAltitude, maximumAirmass: row.maximumAirmass, maximumSunAltitude: row.maximumSunAltitude, minimumMoonSeparation: row.minimumMoonSeparation, minimumContinuousMs: row.minimumContinuousMs })
	const item = { id: row.id, target: targetOf(row), targetName: row.targetName, priority: row.priority, requestedDurationMs: row.requestedDurationMs, notes: row.notes }
	return { ...item, ...(row.scheduledStartAt !== null && { scheduledStartAt: row.scheduledStartAt }), ...(Object.keys(constraints).length > 0 && { constraints }) }
}

// Returns the plan of a row and its items.
function planOf(row: PlanRow, items: readonly ObservingPlanItem[]): ObservingPlan {
	const { id, name, eveningDate, observingSiteId, siteName, latitude, longitude, elevation, timeZone, mode, minimumAltitude, maximumSunAltitude, minimumContinuousMs, revision, createdAt, updatedAt } = row
	const constraints = { mode, minimumAltitude, maximumSunAltitude, minimumContinuousMs, ...defined<Pick<ObservingConstraints, 'maximumAirmass' | 'minimumMoonSeparation'>>({ maximumAirmass: row.maximumAirmass, minimumMoonSeparation: row.minimumMoonSeparation }) }
	const site = { name: siteName, latitude, longitude, elevation, timeZone }
	return { id, name, eveningDate, ...(observingSiteId !== null && { observingSiteId }), site, constraints, items, revision, createdAt, updatedAt }
}

// Night plans of the operational database.
export class ObservingPlanStore {
	// Creates the store over database.
	constructor(readonly database: AppDatabase) {}

	// Returns every plan with its items, most recently changed first.
	list(): ObservingPlan[] {
		const db = this.database.db
		const items = new Map<string, ObservingPlanItem[]>()

		for (const row of db.query<ItemRow, []>(`SELECT ${ITEM_COLUMNS} FROM observing_plan_items ORDER BY plan_id, position`).all()) {
			const list = items.get(row.planId)
			if (list) list.push(itemOf(row))
			else items.set(row.planId, [itemOf(row)])
		}

		return db
			.query<PlanRow, []>(`SELECT ${PLAN_COLUMNS} FROM observing_plans ORDER BY updated_at DESC, id`)
			.all()
			.map((row) => planOf(row, items.get(row.id) ?? []))
	}

	// Returns a plan with its items; undefined when it does not exist.
	get(id: string): ObservingPlan | undefined {
		const db = this.database.db
		const row = db.query<PlanRow, [string]>(`SELECT ${PLAN_COLUMNS} FROM observing_plans WHERE id = ?`).get(id)
		if (!row) return undefined
		const items = db.query<ItemRow, [string]>(`SELECT ${ITEM_COLUMNS} FROM observing_plan_items WHERE plan_id = ? ORDER BY position`).all(id)
		return planOf(row, items.map(itemOf))
	}

	// Saves a whole plan in one transaction when `revision` is the one stored (0 creates it): the plan row, then its items
	// replaced in order, and the revision increased.
	save(id: string, request: ObservingPlanSaveRequest, now: number = Date.now()): ObservingPlanOutcome {
		return this.database.write((): ObservingPlanOutcome => {
			const current = this.get(id)
			if ((current?.revision ?? 0) !== request.revision) return { status: 'conflict', current: current ?? null }
			this.#write(id, request, current ? current.revision + 1 : 1, current?.createdAt ?? now, now)
			return { status: 'saved', plan: this.get(id)! }
		})
	}

	// Copies a plan and its items under a new id and name, as revision 1.
	duplicate(id: string, newId: string, name: string, now: number = Date.now()): ObservingPlanOutcome {
		return this.database.write((): ObservingPlanOutcome => {
			const source = this.get(id)
			if (!source) return { status: 'notFound' }
			if (this.get(newId)) return { status: 'conflict', current: this.get(newId)! }
			this.#write(newId, { ...source, name }, 1, now, now)
			return { status: 'saved', plan: this.get(newId)! }
		})
	}

	// Removes a plan and its items when `revision` is the one stored.
	remove(id: string, revision: number): ObservingPlanRemoval {
		return this.database.write((): ObservingPlanRemoval => {
			const current = this.get(id)
			if (!current) return { status: 'notFound' }
			if (current.revision !== revision) return { status: 'conflict', current }
			this.database.db.query('DELETE FROM observing_plans WHERE id = ?').run(id)
			return { status: 'removed' }
		})
	}

	// Writes a plan row and replaces its items; runs inside a transaction.
	#write(id: string, document: ObservingPlanDocument, revision: number, createdAt: number, updatedAt: number) {
		const db = this.database.db
		const { name, eveningDate, observingSiteId, site, constraints, items } = document

		db.query(
			`INSERT INTO observing_plans (id, name, evening_date, observing_site_id, site_name, latitude, longitude, elevation, time_zone, mode, minimum_altitude, maximum_airmass, maximum_sun_altitude, minimum_moon_separation, minimum_continuous_ms, revision, created_at, updated_at)
			VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
			ON CONFLICT (id) DO UPDATE SET name = excluded.name, evening_date = excluded.evening_date, observing_site_id = excluded.observing_site_id, site_name = excluded.site_name, latitude = excluded.latitude, longitude = excluded.longitude, elevation = excluded.elevation, time_zone = excluded.time_zone, mode = excluded.mode, minimum_altitude = excluded.minimum_altitude, maximum_airmass = excluded.maximum_airmass, maximum_sun_altitude = excluded.maximum_sun_altitude, minimum_moon_separation = excluded.minimum_moon_separation, minimum_continuous_ms = excluded.minimum_continuous_ms, revision = excluded.revision, updated_at = excluded.updated_at`,
		).run(
			id,
			name,
			eveningDate,
			observingSiteId ?? null,
			site.name,
			site.latitude,
			site.longitude,
			site.elevation,
			site.timeZone,
			constraints.mode,
			constraints.minimumAltitude,
			constraints.maximumAirmass ?? null,
			constraints.maximumSunAltitude,
			constraints.minimumMoonSeparation ?? null,
			constraints.minimumContinuousMs,
			revision,
			createdAt,
			updatedAt,
		)

		db.query('DELETE FROM observing_plan_items WHERE plan_id = ?').run(id)

		const insert = db.query(
			'INSERT INTO observing_plan_items (plan_id, id, position, target_kind, catalog_id, body_code, right_ascension, declination, target_name, priority, requested_duration_ms, scheduled_start_at, minimum_altitude, maximum_airmass, maximum_sun_altitude, minimum_moon_separation, minimum_continuous_ms, notes) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)',
		)

		for (const [position, item] of items.entries()) {
			const { target, constraints: override } = item
			insert.run(
				id,
				item.id,
				position,
				target.kind,
				target.kind === 'catalog' ? target.id : null,
				target.kind === 'body' ? target.code : null,
				target.kind === 'coordinates' ? target.rightAscension : null,
				target.kind === 'coordinates' ? target.declination : null,
				target.kind === 'coordinates' ? target.name : item.targetName,
				item.priority,
				item.requestedDurationMs,
				item.scheduledStartAt ?? null,
				override?.minimumAltitude ?? null,
				override?.maximumAirmass ?? null,
				override?.maximumSunAltitude ?? null,
				override?.minimumMoonSeparation ?? null,
				override?.minimumContinuousMs ?? null,
				item.notes,
			)
		}
	}
}
