import type { ObservingSite as SavedObservingSite } from 'api'
import { nanoid } from 'nanoid'
import { parseAngle, toDeg } from 'nebulosa/src/math/units/angle'
import { proxy } from 'valtio'
import { activeProfile, type ProfileState } from '../profile/profile'
import type { Profile } from '../profile/schema'
import { navigate, routeState } from '../shell/route'
import { isKnownTimeZone } from './zone'

// Observing sites of the workspace: named places with their civil time zone, one catalog shared by every profile, tab,
// and browser, which the server keeps (sync.ts of the profiles). Each profile selects the site it observes from
// (Profile.activeSiteId); a tab changes its stores at once and the synchronization writes what changed. Selecting or
// editing a site never commands a device.

// Lowest elevation accepted for a site, in meters (below the Dead Sea shore, -430 m).
export const MIN_SITE_ELEVATION = -500

// Highest elevation accepted for a site, in meters (above Everest, 8849 m).
export const MAX_SITE_ELEVATION = 9000

// Editable fields of an observing site.
export type ObservingSiteInput = Omit<SavedObservingSite, 'id' | 'revision'>

// Observing site of the workspace, as the tab holds it; the synchronization keeps its revision.
export interface ObservingSite extends ObservingSiteInput {
	// Id of the site, generated by the tab that created it.
	readonly id: string
}

// Observing sites of the tab.
export interface SiteState {
	// Saved sites, in list order.
	sites: ObservingSite[]
}

// Site store of the tab, empty until the workspace is loaded.
export const siteState = proxy<SiteState>({ sites: [] })

// Returns the fields of a valid site, the name trimmed, or undefined for a blank name, a coordinate or elevation out of
// range, or a time zone the browser does not know.
export function normalizeObservingSite(input: ObservingSiteInput): ObservingSiteInput | undefined {
	const name = input.name.trim()
	const { latitude, longitude, elevation, timeZone } = input
	if (!name) return undefined
	if (!Number.isFinite(latitude) || latitude < -90 || latitude > 90) return undefined
	if (!Number.isFinite(longitude) || longitude < -180 || longitude > 180) return undefined
	if (!Number.isFinite(elevation) || elevation < MIN_SITE_ELEVATION || elevation > MAX_SITE_ELEVATION) return undefined
	if (!isKnownTimeZone(timeZone)) return undefined
	return { name, latitude, longitude, elevation, timeZone }
}

// Adds a site, or replaces the one with id in place. Returns it, or undefined, changing nothing, for invalid fields.
export function saveSite(state: SiteState, input: ObservingSiteInput, id?: string): ObservingSite | undefined {
	const normalized = normalizeObservingSite(input)
	if (!normalized) return undefined

	const index = state.sites.findIndex((site) => site.id === id)
	const site: ObservingSite = { id: index >= 0 && id ? id : nanoid(), ...normalized }
	if (index >= 0) state.sites[index] = site
	else state.sites.push(site)
	return site
}

// Removes a site from the catalog. Profiles observing from it are cleared by forgetSite.
export function removeSite(state: SiteState, id: string) {
	state.sites = state.sites.filter((site) => site.id !== id)
}

// Forgets a removed site in every profile: those observing from it observe from none, never from another site.
export function forgetSite(state: ProfileState, siteId: string) {
	for (const profile of state.profiles) if (profile.activeSiteId === siteId) delete profile.activeSiteId
}

// Selects the site the active profile observes from; undefined clears it. Ignored for a site that is not saved.
export function selectSite(state: ProfileState, sites: SiteState, siteId: string | undefined) {
	const profile = activeProfile(state)
	if (profile.activeSiteId === siteId) return
	if (siteId === undefined) delete profile.activeSiteId
	else if (sites.sites.some((site) => site.id === siteId)) profile.activeSiteId = siteId
}

// Returns the site a profile observes from, of the state or a snapshot of it; undefined when it has none.
export function activeSite<S extends Pick<ObservingSite, 'id'>>(profile: Pick<Profile, 'activeSiteId'>, sites: readonly S[]): S | undefined {
	return profile.activeSiteId === undefined ? undefined : sites.find((site) => site.id === profile.activeSiteId)
}

// Reads a latitude or a longitude typed by a person, in degrees: decimal ("-23.5475") or sexagesimal ("23° 32′ 51″",
// "23 32 51"), signed or followed (or preceded) by its hemisphere letter, positive for N or E, negative for S or W
// ("23.5475 S"). axis says which letters apply. Returns undefined for a text that is not an angle, or a sign together
// with a hemisphere letter; ranges are checked by normalizeObservingSite.
export function parseGeographicAngle(text: string, axis: 'latitude' | 'longitude'): number | undefined {
	const [positive, negative] = axis === 'latitude' ? ['N', 'S'] : ['E', 'W']
	let value = text.trim().toUpperCase()
	let sign = 1
	const letter = value.endsWith(positive) || value.startsWith(positive) ? positive : value.endsWith(negative) || value.startsWith(negative) ? negative : undefined

	if (letter) {
		value = (value.startsWith(letter) ? value.slice(1) : value.slice(0, -1)).trim()
		if (/^[-+−]/.test(value)) return undefined
		if (letter === negative) sign = -1
	}

	// A hemisphere letter of the other axis, or a second one, is not a coordinate of this one.
	if (/[NSEW]/.test(value)) return undefined

	// Decimal degrees are kept as typed, never through radians, which would add digits to them.
	const decimal = Number(value.replace('−', '-'))
	if (value !== '' && Number.isFinite(decimal)) return sign * decimal

	const angle = parseAngle(value)
	return angle === undefined || !Number.isFinite(angle) ? undefined : (sign * Math.round(toDeg(angle) * SEXAGESIMAL_SCALE)) / SEXAGESIMAL_SCALE
}

// Scale sexagesimal coordinates are rounded to once read, 1e-9° (about 0.1 mm on the Earth), so the floating-point
// noise of the conversion never shows in a field.
const SEXAGESIMAL_SCALE = 1e9

// Opens Settings → Observing Sites on a site, or on the first one; the way every screen sends a person to choose or
// edit where they observe from.
export function openObservingSites(siteId?: string) {
	navigate(routeState, { workspace: 'settings', section: 'observing-sites', site: siteId })
}
