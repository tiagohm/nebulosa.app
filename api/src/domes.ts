import { DomeCommander } from 'nebulosa/src/devices/commanders/dome'
import type { Dome, DomeDirection } from 'nebulosa/src/devices/indi/device'
import type { OperationContext, OperationResult } from 'nebulosa/src/devices/orchestration/operation'
import { deg } from 'nebulosa/src/math/units/angle'
import { type ClientResolver, type CommandRequest, connectedDevice, findDevice, notFound, settle, startCommand, stateResponse, stopResponse, unsupported } from './commands'
import type { DeviceRegistry } from './devices'
import { errorResponse } from './http'
import { DEFAULT_LEASE_OPTIONS, type LeasedMotion, LeasedMotions, type LeasedSession, type LeasedStartResponse, type LeaseOptions } from './leases'
import type { OperationRegistry } from './operations'

// Dome commands of every open connection, over the toolkit's DomeCommander: a slew to an azimuth, a
// rotation by an angle, a move of the shutter to an altitude, a search for the home position, park and
// unpark, opening and closing the shutter, the driver's own slaving to the mount, the rotation speed, the
// backlash compensation, a sync of the azimuth, the park position, and a stop. Angles cross the API in
// degrees and the toolkit in radians. Motions run as dome.* operations that resolve once the dome reports
// the commanded state; while the driver slaves the dome to the mount, the commander refuses every motion,
// so slaving has to be switched off first. Manual rotation is a press held by a lease, exactly like a
// mount nudge (leases.ts), run as a dome.move operation; its sessions are published as dome:motion events.
// The interlocks of the driver are respected: nothing here bypasses a refusal of the commander.

// Body of POST /api/connections/:id/domes/:deviceId/slew.
export interface DomeSlewRequest extends CommandRequest {
	// Target azimuth in degrees from north through east.
	readonly azimuth: number
}

// Body of POST /api/connections/:id/domes/:deviceId/move-by.
export interface DomeMoveByRequest extends CommandRequest {
	// Rotation in degrees; positive is clockwise, seen from above.
	readonly delta: number
}

// Body of POST /api/connections/:id/domes/:deviceId/altitude.
export interface DomeAltitudeRequest extends CommandRequest {
	// Target shutter altitude in degrees.
	readonly altitude: number
}

// Body of POST /api/connections/:id/domes/:deviceId/shutter.
export interface DomeShutterRequest extends CommandRequest {
	// Whether the shutter is to be open.
	readonly open: boolean
}

// Body of POST /api/connections/:id/domes/:deviceId/slaving.
export interface DomeSlavingRequest {
	// Whether the driver is to follow the mount.
	readonly enabled: boolean
}

// Body of POST /api/connections/:id/domes/:deviceId/sync.
export interface DomeSyncRequest {
	// Azimuth in degrees the dome is to report where it stands, without moving.
	readonly azimuth: number
}

// Body of POST /api/connections/:id/domes/:deviceId/speed.
export interface DomeSpeedRequest {
	// Rotation speed in RPM; the commander keeps it inside the range the driver publishes.
	readonly value: number
}

// Body of POST /api/connections/:id/domes/:deviceId/backlash.
export interface DomeBacklashRequest {
	// Whether backlash compensation is to be on; unchanged when absent.
	readonly enabled?: boolean
	// Backlash compensation in controller steps; unchanged when absent.
	readonly steps?: number
}

// Body of POST /api/connections/:id/domes/:deviceId/motion.
export interface DomeMotionRequest {
	// Identity of this press, generated by the tab and unique per press.
	readonly token: string
	// Direction to rotate in.
	readonly direction: DomeDirection
}

// Manual rotation session as published to clients.
export interface DomeMotionSession extends LeasedSession {
	// Direction rotated in.
	readonly direction: DomeDirection
}

// Response of an accepted manual rotation.
export type DomeMotionStartResponse = LeasedStartResponse<DomeMotionSession>

// Notification published on every change of a manual rotation session, its end included.
export type DomeMotionEvent = { readonly type: 'dome:motion'; readonly session: DomeMotionSession }

// Receiver of manual rotation events.
export type DomeMotionListener = (event: DomeMotionEvent) => void

// Returns why a dome cannot rotate manually now, or undefined when it can.
function motionRefusal(dome: Dome): Response | undefined {
	if (!dome.connected) return errorResponse('The dome is disconnected', 409, 'disconnected')
	if (!dome.canMove) return unsupported('The dome cannot rotate manually')
	if (dome.slaved) return errorResponse('The dome follows the mount; switch slaving off first', 409, 'unsupported')
	if (dome.parked || dome.parking) return errorResponse('The dome is parked', 409, 'unsupported')
	return undefined
}

// Returns why a dome cannot start a motion now, or undefined when it can.
function slewRefusal(dome: Dome): Response | undefined {
	if (dome.slaved) return errorResponse('The dome follows the mount; switch slaving off first', 409, 'unsupported')
	if (dome.parked || dome.parking) return errorResponse('The dome is parked', 409, 'unsupported')
	return undefined
}

// Dome commands over the domes of every open connection.
export class DomeCommands implements Disposable {
	// Commander driving the domes and observing their motion.
	readonly #commander: DomeCommander
	// Manual rotation sessions of every dome.
	readonly #motions: LeasedMotions<DomeMotionSession>

	// Creates the commands over the device registry; client resolves an open connection id to its client,
	// operations runs and publishes every motion, listener receives every manual rotation event
	// synchronously, and lease sets the lease timing of manual rotations.
	constructor(
		readonly devices: DeviceRegistry,
		readonly client: ClientResolver,
		readonly operations: OperationRegistry,
		listener: DomeMotionListener,
		lease: LeaseOptions = DEFAULT_LEASE_OPTIONS,
	) {
		this.#commander = new DomeCommander(devices.domes)
		this.#motions = new LeasedMotions<DomeMotionSession>(operations, 'dome.move', 'domeManualMove', { motion: 'rotation', device: 'dome' }, (session) => listener({ type: 'dome:motion', session }), lease)
	}

	// Responds with the state of a dome, or 404.
	state(connectionId: string, deviceId: string): Response {
		return stateResponse(this.devices, this.client, connectionId, 'dome', deviceId, 'Dome')
	}

	// Returns the manual rotation sessions still running, in start order.
	motions(): DomeMotionSession[] {
		return this.#motions.sessions()
	}

	// Starts a slew to an azimuth. Responds 202 with the operation id; 404, 409 disconnected, slaved,
	// parked, or busy, 422 when the dome cannot slew to an azimuth.
	slew(connectionId: string, deviceId: string, request: DomeSlewRequest): Response {
		const dome = this.#connected(connectionId, deviceId)
		if (dome instanceof Response) return dome
		if (!dome.canSetAzimuth) return unsupported('The dome cannot slew to an azimuth')
		return slewRefusal(dome) ?? startCommand(this.operations, 'dome.slew', connectionId, dome, request, () => this.#commander.moveTo(this.operations.coordinator, dome, deg(request.azimuth)))
	}

	// Starts a rotation by an angle; answered like slew, with 422 when the dome cannot rotate by an angle. A
	// repeated request with the same token never rotates it twice.
	moveBy(connectionId: string, deviceId: string, request: DomeMoveByRequest): Response {
		const dome = this.#connected(connectionId, deviceId)
		if (dome instanceof Response) return dome
		if (!dome.canRelativeMove) return unsupported('The dome cannot rotate by an angle')
		return slewRefusal(dome) ?? startCommand(this.operations, 'dome.slew', connectionId, dome, request, () => this.#commander.moveBy(this.operations.coordinator, dome, deg(request.delta)))
	}

	// Starts a move of the shutter to an altitude; answered like slew, with 422 when the dome cannot.
	moveToAltitude(connectionId: string, deviceId: string, request: DomeAltitudeRequest): Response {
		const dome = this.#connected(connectionId, deviceId)
		if (dome instanceof Response) return dome
		if (!dome.canSetAltitude) return unsupported('The dome cannot move its shutter to an altitude')
		return slewRefusal(dome) ?? startCommand(this.operations, 'dome.slew', connectionId, dome, request, () => this.#commander.moveToAltitude(this.operations.coordinator, dome, deg(request.altitude)))
	}

	// Starts the search for the home position. Responds 202 with the operation id; 404, 409, 422 when the
	// dome cannot search it.
	home(connectionId: string, deviceId: string, request: CommandRequest): Response {
		const dome = this.#connected(connectionId, deviceId)
		if (dome instanceof Response) return dome
		if (!dome.canFindHome) return unsupported('The dome cannot search its home position')
		return slewRefusal(dome) ?? startCommand(this.operations, 'dome.home', connectionId, dome, request, () => this.#commander.home(this.operations.coordinator, dome))
	}

	// Starts parking. Responds 202 with the operation id; 404, 409 disconnected, slaved, or busy, 422 when the
	// dome cannot park.
	park(connectionId: string, deviceId: string, request: CommandRequest): Response {
		const dome = this.#connected(connectionId, deviceId)
		if (dome instanceof Response) return dome
		if (!dome.canPark) return unsupported('The dome cannot park')
		if (dome.slaved) return errorResponse('The dome follows the mount; switch slaving off first', 409, 'unsupported')
		return startCommand(this.operations, 'dome.park', connectionId, dome, request, () => this.#commander.park(this.operations.coordinator, dome))
	}

	// Starts unparking; answered like park, with 422 when the dome cannot unpark.
	unpark(connectionId: string, deviceId: string, request: CommandRequest): Response {
		const dome = this.#connected(connectionId, deviceId)
		if (dome instanceof Response) return dome
		if (!dome.canUnpark) return unsupported('The dome cannot unpark')
		return startCommand(this.operations, 'dome.unpark', connectionId, dome, request, () => this.#commander.unpark(this.operations.coordinator, dome))
	}

	// Starts opening or closing the shutter. Responds 202 with the operation id; 404, 409, 422 when the dome
	// has no shutter it can command.
	shutter(connectionId: string, deviceId: string, request: DomeShutterRequest): Response {
		const dome = this.#connected(connectionId, deviceId)
		if (dome instanceof Response) return dome
		if (!dome.hasShutter || !dome.canSetShutter) return unsupported('The dome has no shutter it can open or close')
		const { coordinator } = this.operations
		return startCommand(this.operations, 'dome.shutter', connectionId, dome, request, () => (request.open ? this.#commander.openShutter(coordinator, dome) : this.#commander.closeShutter(coordinator, dome)))
	}

	// Switches the driver's slaving to the mount and responds 204 once the dome reports it; 404, 409, 422
	// when the driver cannot slave the dome.
	async setSlaving(connectionId: string, deviceId: string, { enabled }: DomeSlavingRequest): Promise<Response> {
		const dome = this.#connected(connectionId, deviceId)
		if (dome instanceof Response) return dome
		if (!dome.canSlave) return unsupported('The dome cannot follow the mount')
		return await settle(this.#commander.slave(this.operations.coordinator, dome, enabled), 'Switching slaving')
	}

	// Redefines the azimuth without moving. Responds 204 once sent; 404, 409, 422 when the dome cannot sync.
	async sync(connectionId: string, deviceId: string, { azimuth }: DomeSyncRequest): Promise<Response> {
		const dome = this.#connected(connectionId, deviceId)
		if (dome instanceof Response) return dome
		if (!dome.canSync) return unsupported('The dome cannot sync its azimuth')
		return await settle(this.#commander.syncTo(this.operations.coordinator, dome, deg(azimuth)), 'The sync')
	}

	// Stores the current position as the park position. Responds 204 once sent; 404, 409, 422 when the dome
	// cannot.
	async setPark(connectionId: string, deviceId: string): Promise<Response> {
		const dome = this.#connected(connectionId, deviceId)
		if (dome instanceof Response) return dome
		if (!dome.canSetPark) return unsupported('The dome cannot store its park position')
		return await settle(this.#commander.setPark(this.operations.coordinator, dome), 'Setting the park position')
	}

	// Sets the rotation speed. Responds 204 once sent; 404, 409, 422 when the speed cannot be set.
	async setSpeed(connectionId: string, deviceId: string, { value }: DomeSpeedRequest): Promise<Response> {
		const dome = this.#connected(connectionId, deviceId)
		if (dome instanceof Response) return dome
		if (!dome.canSetSpeed) return unsupported('The dome cannot set its speed')
		return await settle(this.#commander.setSpeed(this.operations.coordinator, dome, value), 'Setting the speed')
	}

	// Switches backlash compensation and sets its steps, whichever the request carries. Responds 204 once
	// sent; 404, 409, 422 when the dome has no backlash compensation.
	async setBacklash(connectionId: string, deviceId: string, { enabled, steps }: DomeBacklashRequest): Promise<Response> {
		const dome = this.#connected(connectionId, deviceId)
		if (dome instanceof Response) return dome
		if (!dome.hasBacklash) return unsupported('The dome has no backlash compensation')

		const { coordinator } = this.operations

		if (enabled !== undefined) {
			const switched = await settle(this.#commander.setBacklash(coordinator, dome, enabled), 'Switching backlash compensation')
			if (switched.status !== 204 || steps === undefined) return switched
		}

		return steps === undefined ? new Response(null, { status: 204 }) : await settle(this.#commander.setBacklashSteps(coordinator, dome, steps), 'Setting the backlash')
	}

	// Cancels the operation holding a dome, a manual rotation included, and stops its motion and its
	// shutter. Responds 204 once it stands still, 404, and 409 when the stop could not be confirmed.
	async stop(connectionId: string, deviceId: string): Promise<Response> {
		const dome = findDevice(this.devices, this.client, connectionId, 'dome', deviceId)
		if (!dome) return notFound('Dome')
		return await stopResponse(this.operations, dome, () => this.#commander.stopMotion(dome))
	}

	// Starts a manual rotation held by a lease, answered like a mount nudge (see LeasedMotions.start): 202
	// with the session and the lease timing, 404, 409 disconnected, slaved, parked, busy, or already stopped,
	// 422 when the dome cannot rotate manually, 502 when the command could not be sent.
	async startMotion(connectionId: string, deviceId: string, { token, direction }: DomeMotionRequest): Promise<Response> {
		const dome = findDevice(this.devices, this.client, connectionId, 'dome', deviceId)
		if (!dome) return notFound('Dome')
		return await this.#motions.start(
			dome,
			{ token, connectionId, deviceId, direction },
			() => motionRefusal(dome),
			(context, motion) => this.#rotate(context, dome, direction, motion),
		)
	}

	// Renews the lease of a running manual rotation; 404 when it no longer runs.
	heartbeatMotion(token: string): Response {
		return this.#motions.heartbeat(token)
	}

	// Ends a manual rotation and resolves once the dome stopped; never refused.
	async stopMotion(token: string): Promise<Response> {
		return await this.#motions.stop(token)
	}

	// Returns the connected dome with this id on an open connection, or the response refusing it.
	#connected(connectionId: string, deviceId: string): Dome | Response {
		return connectedDevice(this.devices, this.client, connectionId, 'dome', deviceId, 'Dome')
	}

	// Runs a manual rotation: starts the direction through a nested manual motion, which inherits the dome,
	// and keeps it until the session is asked to end. The commander's cleanup stops the dome.
	async #rotate(context: OperationContext, dome: Dome, direction: DomeDirection, motion: LeasedMotion): Promise<OperationResult<void>> {
		const started = await this.#commander.startManualMove(context, dome, direction)

		// A command that failed to send may still have reached the driver, so the end has to verify the stop.
		if (started.ok || started.reason === 'commandFailed') motion.commanded()
		if (!started.ok) return started

		motion.moving()
		await motion.ending
		return await started.value.stop()
	}

	// Stops observing the domes and the leases of manual rotations; their operations belong to the
	// operation registry, whose disposal cancels them.
	[Symbol.dispose]() {
		this.#motions[Symbol.dispose]()
		this.#commander.dispose()
	}
}
