import type { CatalogSource } from 'nebulosa/src/devices/indi/simulator/types'
import boundaries from '../../data/constellation.boundaries.json'
import labels from '../../data/constellation.labels.json'
import lines from '../../data/constellation.lines.json'
import catalog from '../../data/sky.catalog.db' with { embed: 'true', type: 'sqlite' }
import type { AnnotationSky } from '../annotations'
import { createActiveRegionRoutes, SolarActiveRegions } from './activeregions'
import { type ConstellationSource, catalogStars, fieldConstellations, fieldObjects } from './catalog'
import { SkyEphemeris } from './ephemeris'
import { MinorBodies } from './minorbodies'
import { createMoonAlmanacRoutes, MoonAlmanac } from './moon'
import { createSkyLocator, createSkyRoutes, type SkyServices } from './routes'
import { assertSkyCatalogSchema } from './schema'
import { createSolarImageRoutes, SolarImages } from './sdo'
import { createSunAlmanacRoutes, SunAlmanac } from './sun'

// Sky API wired to the embedded sky catalog (generated by `bun make:catalog`), the constellation data
// of api/data, JPL Horizons, and SBDB, plus the Sun Inspector's almanac and its NASA SDO and NOAA SWPC sources and the Moon Inspector's almanac. This is the only module that loads them, so the rest of the sky API stays testable with
// in-memory data.

assertSkyCatalogSchema(catalog)

// J2000 constellation figures, boundaries, and labels.
const constellations: ConstellationSource = { lines, labels, boundaries }

// Services shared by the sky routes and the sky locator.
const services: SkyServices = { catalog, constellations, ephemeris: new SkyEphemeris(), minorBodies: new MinorBodies() }

// Sky data of the image annotation: the J2000 objects and figures of a field.
export const annotationSky: AnnotationSky = {
	objects: (query) => fieldObjects(catalog, query),
	constellations: (rightAscension, declination, radius) => fieldConstellations(constellations, rightAscension, declination, radius),
}

// Routes of the sky API, with those of the Sun and Moon Inspectors.
export const skyRoutes = { ...createSkyRoutes(services), ...createSunAlmanacRoutes(new SunAlmanac()), ...createMoonAlmanacRoutes(new MoonAlmanac()), ...createSolarImageRoutes(new SolarImages()), ...createActiveRegionRoutes(new SolarActiveRegions()) }

// Locator of the objects of the sky API, used to resolve mount targets.
export const skyLocator = createSkyLocator(services)

// Stars of the sky catalog around a J2000 cone, the catalog source of the simulated camera.
export const skyStarSource: CatalogSource = (rightAscension, declination, radius) => catalogStars(catalog, rightAscension, declination, radius)
