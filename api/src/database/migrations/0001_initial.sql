-- Baseline schema of the operational database of Nebulosa.
--
-- While the application is in development this file is edited in place: a database whose baseline checksum differs is
-- deleted and created again. Tables are STRICT; times are Unix milliseconds (UTC); every column states its unit.

-- Migrations applied to the database, one row per version.
CREATE TABLE schema_migrations (
	-- Position of the migration in the history, from 1.
	version INTEGER PRIMARY KEY,
	-- SHA-256 of its statements, in lowercase hexadecimal.
	checksum TEXT NOT NULL,
	-- When it was applied, Unix milliseconds (UTC).
	applied_at INTEGER NOT NULL
) STRICT;

-- Settings of the external programs and services of the server (ExternalToolsStore). A program without a row has
-- never been saved and runs with the defaults. The session of a web service is never stored.
CREATE TABLE external_tool_settings (
	-- Supported program.
	tool_id TEXT PRIMARY KEY CHECK (tool_id IN ('astap', 'astrometryLocal', 'nova')),
	-- Path or PATH name of the executable on the server; empty when not configured or not taken.
	executable TEXT NOT NULL,
	-- Default time limit of a run, in milliseconds.
	timeout INTEGER NOT NULL CHECK (timeout > 0),
	-- Path of the configuration file passed to the program; NULL when the program takes none.
	config TEXT,
	-- Base URL of a web service; NULL when the program is not one.
	endpoint TEXT,
	-- Revision of the settings, increased by every save, sign-in, and sign-out; >= 1.
	revision INTEGER NOT NULL CHECK (revision > 0),
	-- When the settings last changed, Unix milliseconds (UTC).
	updated_at INTEGER NOT NULL
) STRICT;

-- Backlash compensation of each physical focuser (FocuserBacklashStore), by its connection id and device id, both stable
-- across restarts and reconnects of the same endpoint. A focuser without a row has never been saved: compensation off.
CREATE TABLE focuser_backlash (
	-- Id of the connection of the focuser (the hash of its endpoint).
	connection_id TEXT NOT NULL,
	-- Id of the focuser on its connection.
	device_id TEXT NOT NULL,
	-- Whether the moves are compensated, 0 or 1.
	enabled INTEGER NOT NULL CHECK (enabled IN (0, 1)),
	-- Compensation strategy.
	mode TEXT NOT NULL CHECK (mode IN ('ABSOLUTE', 'OVERSHOOT')),
	-- Backlash absorbed when reversing into the IN direction, in steps.
	backlash_in INTEGER NOT NULL CHECK (backlash_in >= 0),
	-- Backlash absorbed when reversing into the OUT direction, in steps.
	backlash_out INTEGER NOT NULL CHECK (backlash_out >= 0),
	-- Revision of the settings, increased by every save; >= 1.
	revision INTEGER NOT NULL CHECK (revision > 0),
	-- When the settings last changed, Unix milliseconds (UTC).
	updated_at INTEGER NOT NULL,
	PRIMARY KEY (connection_id, device_id)
) STRICT;

-- Connections saved by the operators (Workspace), shared by every tab and browser: definitions only, never the open
-- connections of the server. Ids are generated by the tab that created them.
CREATE TABLE saved_connections (
	-- Id of the saved connection.
	id TEXT PRIMARY KEY,
	-- Name shown to people.
	name TEXT NOT NULL CHECK (length(trim(name)) > 0),
	-- Backend the connection opens.
	type TEXT NOT NULL CHECK (type IN ('INDI', 'ALPACA', 'SIMULATOR')),
	-- Host of the endpoint; empty for the simulator.
	host TEXT NOT NULL,
	-- TCP port of the endpoint.
	port INTEGER NOT NULL CHECK (port BETWEEN 0 AND 65535),
	-- Position in the list, ascending.
	sort_order INTEGER NOT NULL,
	-- Revision, increased by every save; >= 1.
	revision INTEGER NOT NULL CHECK (revision > 0),
	-- When it was created and last changed, Unix milliseconds (UTC).
	created_at INTEGER NOT NULL,
	updated_at INTEGER NOT NULL
) STRICT;

-- Profiles of the operators (Workspace), shared by every tab and browser. Ids are generated by the tab that created
-- them. Which profile a tab works with is the tab's own and never stored.
CREATE TABLE profiles (
	-- Id of the profile.
	id TEXT PRIMARY KEY,
	-- Name shown to people.
	name TEXT NOT NULL CHECK (length(trim(name)) > 0),
	-- Saved connection the profile works with; NULL when none, or when it was deleted.
	connection_id TEXT REFERENCES saved_connections (id) ON DELETE SET NULL,
	-- Position in the list, ascending.
	sort_order INTEGER NOT NULL,
	-- Revision of the name, connection, and position, increased by every save; >= 1.
	revision INTEGER NOT NULL CHECK (revision > 0),
	-- When it was created and last changed, Unix milliseconds (UTC).
	created_at INTEGER NOT NULL,
	updated_at INTEGER NOT NULL
) STRICT;

-- Device each role of a profile's equipment setup takes on a saved connection.
CREATE TABLE profile_equipment (
	profile_id TEXT NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
	saved_connection_id TEXT NOT NULL REFERENCES saved_connections (id) ON DELETE CASCADE,
	-- Operational role (EquipmentRole of the web).
	role TEXT NOT NULL CHECK (role IN ('MAIN_CAMERA', 'GUIDE_CAMERA', 'MOUNT', 'FOCUSER', 'FILTER_WHEEL', 'ROTATOR', 'GUIDE_OUTPUT', 'DOME', 'COVER', 'FLAT_PANEL')),
	-- Id of the device on the connection, and its name when assigned.
	device_id TEXT NOT NULL,
	device_name TEXT NOT NULL,
	PRIMARY KEY (profile_id, saved_connection_id, role)
) STRICT;

-- Preferences of a profile, one JSON value per key, in the shape and version of the web (PROFILE_SETTINGS_VERSION); a
-- value of another version is read as absent.
CREATE TABLE profile_preferences (
	profile_id TEXT NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
	-- Preference (ProfilePreferenceKey).
	key TEXT NOT NULL CHECK (key IN ('telescope', 'guideTelescope', 'skyObserver', 'skyDisplay', 'skyFraming', 'starDetection', 'starProfile', 'streakDetection', 'imageAnnotation', 'imagePlateSolving', 'imageDisplay', 'imageAstrometry', 'statusBar')),
	-- Version of the shape of the value.
	version INTEGER NOT NULL,
	-- Value; null when reset to its default.
	value TEXT NOT NULL CHECK (json_valid(value)),
	-- Revision, increased by every save; >= 1.
	revision INTEGER NOT NULL CHECK (revision > 0),
	-- When it last changed, Unix milliseconds (UTC).
	updated_at INTEGER NOT NULL,
	PRIMARY KEY (profile_id, key)
) STRICT;

-- Forms of a physical camera in a profile, by saved connection and device id, one JSON value per form.
CREATE TABLE profile_camera_settings (
	profile_id TEXT NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
	saved_connection_id TEXT NOT NULL REFERENCES saved_connections (id) ON DELETE CASCADE,
	device_id TEXT NOT NULL,
	-- Form (ProfileCameraForm).
	form TEXT NOT NULL CHECK (form IN ('exposure', 'acquisition', 'plateSolving', 'autoFocus', 'tppa', 'pointingModel', 'targetCentering', 'darv', 'flatWizard', 'darkLibraryWizard', 'guiding', 'display')),
	-- Version of the shape of the value.
	version INTEGER NOT NULL,
	-- Value; null when reset to its default.
	value TEXT NOT NULL CHECK (json_valid(value)),
	-- Revision, increased by every save; >= 1.
	revision INTEGER NOT NULL CHECK (revision > 0),
	-- When it last changed, Unix milliseconds (UTC).
	updated_at INTEGER NOT NULL,
	PRIMARY KEY (profile_id, saved_connection_id, device_id, form)
) STRICT;

-- Host and port a Mount Remote Control listener of a mount was last started with in a profile. A preference only: it
-- never starts, stops, or rebinds a listener.
CREATE TABLE profile_mount_bindings (
	profile_id TEXT NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
	saved_connection_id TEXT NOT NULL REFERENCES saved_connections (id) ON DELETE CASCADE,
	device_id TEXT NOT NULL,
	protocol TEXT NOT NULL CHECK (protocol IN ('lx200', 'stellarium')),
	-- Address and TCP port the listener binds to.
	host TEXT NOT NULL,
	port INTEGER NOT NULL CHECK (port BETWEEN 0 AND 65535),
	PRIMARY KEY (profile_id, saved_connection_id, device_id, protocol)
) STRICT;

-- Targets a profile saved to recover a framing: a name and a J2000 position, never an image.
CREATE TABLE framing_references (
	-- Id of the framing, generated by the tab that saved it.
	id TEXT PRIMARY KEY,
	profile_id TEXT NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
	-- Name shown to people.
	name TEXT NOT NULL CHECK (length(trim(name)) > 0),
	-- J2000 right ascension and declination, in radians.
	right_ascension REAL NOT NULL,
	declination REAL NOT NULL,
	-- Where the position came from.
	source TEXT NOT NULL CHECK (source IN ('manual', 'sky')),
	-- When it was saved and last renamed, Unix milliseconds (UTC).
	created_at INTEGER NOT NULL,
	updated_at INTEGER NOT NULL
) STRICT;

CREATE INDEX framing_references_profile ON framing_references (profile_id);

-- Notification history of the server (NotificationService): at most 500 records younger than 30 days, the oldest
-- deleted first. The sequence orders them and is never used again.
CREATE TABLE notifications (
	-- Order of creation.
	sequence INTEGER PRIMARY KEY AUTOINCREMENT,
	-- Id of the notification, published to clients.
	id TEXT NOT NULL UNIQUE,
	-- Identity of the occurrence it reports, so one occurrence is notified once; never published.
	key TEXT NOT NULL UNIQUE,
	-- When it was created, Unix milliseconds (UTC).
	created_at INTEGER NOT NULL,
	-- Severity.
	level TEXT NOT NULL CHECK (level IN ('info', 'success', 'warning', 'error')),
	-- Stable code of the occurrence, such as capture.completed.
	code TEXT NOT NULL,
	-- Title and explanation meant for people.
	title TEXT NOT NULL,
	message TEXT NOT NULL,
	-- What it is about (NotificationSource), and the context the UI may open (NotificationTarget) or NULL.
	source TEXT NOT NULL CHECK (json_valid(source)),
	target TEXT CHECK (target IS NULL OR json_valid(target))
) STRICT;

CREATE INDEX notifications_created ON notifications (created_at);

-- Notifications a profile read or dismissed, deleted with the notification or the profile.
CREATE TABLE profile_notification_state (
	profile_id TEXT NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
	notification_id TEXT NOT NULL REFERENCES notifications (id) ON DELETE CASCADE,
	-- When it was read and dismissed, Unix milliseconds (UTC); dismissed_at is NULL while listed.
	read_at INTEGER NOT NULL,
	dismissed_at INTEGER,
	PRIMARY KEY (profile_id, notification_id)
) STRICT;

-- Saved frames of every camera (CaptureFrameRegistry): one row per frame whose file was written, kept until deleted,
-- whatever the Images workspace shows of them. Never pixels; previewed-only frames are never written.
CREATE TABLE capture_frames (
	-- Identity of the frame: its session id and generation.
	frame_id TEXT PRIMARY KEY,
	-- Order of the frame among every frame of the registry.
	sequence INTEGER NOT NULL UNIQUE,
	-- Camera: id of its connection, exact device id, and driver-reported name.
	connection_id TEXT NOT NULL,
	device_id TEXT NOT NULL,
	camera_name TEXT NOT NULL,
	-- Operation that took it (CaptureFrameOrigin).
	origin TEXT NOT NULL,
	-- Session that took it, and the number of the frame in it from 1.
	session_id TEXT NOT NULL,
	generation INTEGER NOT NULL,
	-- When its exposure was commanded, Unix milliseconds (UTC).
	time INTEGER NOT NULL,
	-- Frame type the capture requested.
	frame_type TEXT NOT NULL,
	-- Width and height in pixels, number of channels, FITS BITPIX, and CFA pattern; NULL when never decoded.
	width INTEGER,
	height INTEGER,
	channels INTEGER,
	bitpix INTEGER,
	cfa TEXT,
	-- Acquisition data read from the header (ImageAcquisition); NULL when never decoded.
	acquisition TEXT CHECK (acquisition IS NULL OR json_valid(acquisition)),
	-- Absolute path of the saved file; never sent to clients.
	path TEXT NOT NULL
) STRICT;

CREATE INDEX capture_frames_camera ON capture_frames (connection_id, device_id, sequence);

-- Device operations of the server (OperationRecorder): when each started and how it ended, for 90 days and at most
-- 10000 rows. An operation still running when the server stopped is interrupted. Never the error text, which may hold
-- server paths.
CREATE TABLE operation_runs (
	-- Id of the operation.
	operation_id TEXT PRIMARY KEY,
	-- Kind of operation (OperationKind).
	kind TEXT NOT NULL,
	-- Devices it held, with their names when it started: [{ connectionId, deviceId, name }].
	devices TEXT NOT NULL CHECK (json_valid(devices)),
	-- Outcome; running until it ends.
	state TEXT NOT NULL CHECK (state IN ('running', 'succeeded', 'failed', 'interrupted')),
	-- Why it failed (OperationFailureReason); NULL otherwise.
	reason TEXT,
	-- When it started and ended, Unix milliseconds (UTC); ended_at is NULL while running.
	started_at INTEGER NOT NULL,
	ended_at INTEGER
) STRICT;

CREATE INDEX operation_runs_started ON operation_runs (started_at);

-- Mount pointing models (PointingModelStore): what was measured for each model and every fit of it, never pixels nor
-- whether a revision is active, which lives in server memory. Samples, revisions, and verifications are immutable once
-- written: a refit or an exclusion adds a revision. Kept until the operator deletes the model.
CREATE TABLE pointing_models (
	-- Id of the model.
	model_id TEXT PRIMARY KEY,
	-- Revision of the model, raised by every save; a save from another revision is refused.
	revision INTEGER NOT NULL,
	-- Name the operator reads, and their notes; notes is NULL when there are none.
	label TEXT NOT NULL,
	notes TEXT,
	-- Where the samples came from.
	origin TEXT NOT NULL CHECK (origin IN ('session', 'import')),
	-- Physical mount (PointingMountIdentity), site (PointingSite), optical evidence (PointingOpticsFingerprint), and plan
	-- of the acquisition (PointingPlanRecord); angles in radians, elevations in meters.
	mount TEXT NOT NULL CHECK (json_valid(mount)),
	site TEXT NOT NULL CHECK (json_valid(site)),
	optics TEXT NOT NULL CHECK (json_valid(optics)),
	plan TEXT NOT NULL CHECK (json_valid(plan)),
	-- Latest acquisition of the samples: its session and state. A running or paused one is interrupted at start.
	acquisition_session_id TEXT NOT NULL,
	acquisition_state TEXT NOT NULL CHECK (acquisition_state IN ('running', 'paused', 'interrupted', 'completed', 'stopped')),
	-- When it was created, last saved, and when a revision of it was last active (NULL when never), Unix milliseconds
	-- (UTC).
	created_at INTEGER NOT NULL,
	updated_at INTEGER NOT NULL,
	last_active_at INTEGER
) STRICT;

-- Attempts at the waypoints of a model, in the order they were taken.
CREATE TABLE pointing_samples (
	model_id TEXT NOT NULL REFERENCES pointing_models (model_id) ON DELETE CASCADE,
	-- Id of the attempt, unique in the model.
	sample_id TEXT NOT NULL,
	-- Order of the attempt in the model, from 0.
	position INTEGER NOT NULL,
	-- The attempt (PointingSampleRecord); angles in radians, times in Unix milliseconds.
	record TEXT NOT NULL CHECK (json_valid(record)),
	PRIMARY KEY (model_id, sample_id),
	UNIQUE (model_id, position)
) STRICT;

-- Fits of a model, in the order they were made.
CREATE TABLE pointing_revisions (
	model_id TEXT NOT NULL REFERENCES pointing_models (model_id) ON DELETE CASCADE,
	-- Id of the revision.
	revision_id TEXT NOT NULL,
	-- Order of the fit in the model, from 0.
	position INTEGER NOT NULL,
	-- The fit (PointingRevision without its verifications); a coefficient that is not finite is null.
	record TEXT NOT NULL CHECK (json_valid(record)),
	PRIMARY KEY (model_id, revision_id),
	UNIQUE (model_id, position)
) STRICT;

-- Physical verifications of a revision, in the order they ended.
CREATE TABLE pointing_verifications (
	model_id TEXT NOT NULL,
	revision_id TEXT NOT NULL,
	-- Id of the verification.
	verification_id TEXT NOT NULL,
	-- Order of the verification in its revision, from 0.
	position INTEGER NOT NULL,
	-- The verification (PointingVerification); RMS distances in radians.
	record TEXT NOT NULL CHECK (json_valid(record)),
	PRIMARY KEY (model_id, revision_id, verification_id),
	UNIQUE (model_id, revision_id, position),
	FOREIGN KEY (model_id, revision_id) REFERENCES pointing_revisions (model_id, revision_id) ON DELETE CASCADE
) STRICT;

-- Plans of the Dark Library Wizard (DarkPlanStore): the immutable specification of each plan, the state of its latest
-- session, and every frame it published or quarantined. A frame counts only once committed: it is recorded as
-- publishing before its file is linked, and a plan left with such a frame, or running or paused, is reconciled from the
-- files when the server starts. The frames themselves are files of the output directory. Kept until deleted by hand.
CREATE TABLE dark_plans (
	-- Id of the plan.
	plan_id TEXT PRIMARY KEY,
	-- When it was created, Unix milliseconds (UTC).
	created_at INTEGER NOT NULL,
	-- Absolute directory the frames are saved under.
	directory TEXT NOT NULL,
	-- What the frames are for: NULL for an ordinary dark.
	purpose TEXT CHECK (purpose IS NULL OR purpose = 'darkFlat'),
	-- Whether the Calibration Library builds the masters of the complete groups once the acquisition ends (0 or 1).
	generate_masters INTEGER NOT NULL CHECK (generate_masters IN (0, 1)),
	-- The rest of the specification: camera, protection devices, capture settings, protection, thermal protocol, and
	-- rejections allowed per group (DarkCapturePlan without its id, creation, directory, groups, purpose, and masters).
	spec TEXT NOT NULL CHECK (json_valid(spec)),
	-- State of the acquisition, why the latest session ended (NULL when nothing says), and the session and operation
	-- recorded last (NULL before any).
	status TEXT NOT NULL CHECK (status IN ('running', 'paused', 'interrupted', 'completed', 'stopped', 'failed')),
	status_reason TEXT,
	session_id TEXT,
	operation_id TEXT,
	-- What the latest session could not restore: [text].
	cleanup_warnings TEXT NOT NULL CHECK (json_valid(cleanup_warnings)),
	-- When the state, the frames that count, or the cleanup warnings last changed, Unix milliseconds (UTC).
	updated_at INTEGER NOT NULL
) STRICT;

-- Groups of a plan, in acquisition order.
CREATE TABLE dark_groups (
	plan_id TEXT NOT NULL REFERENCES dark_plans (plan_id) ON DELETE CASCADE,
	-- Id of the group, unique in the plan.
	group_id TEXT NOT NULL,
	-- Order of the group in the plan, from 0.
	position INTEGER NOT NULL,
	-- Exact identity of the settings of its frames (darkGroupKey).
	key TEXT NOT NULL,
	-- Exposure in seconds, and target sensor temperature in degrees Celsius (NULL when not controlled).
	exposure REAL NOT NULL,
	temperature REAL,
	-- Accepted frames required; at least 1.
	count INTEGER NOT NULL,
	-- Absolute directory of its frames.
	directory TEXT NOT NULL,
	PRIMARY KEY (plan_id, group_id),
	UNIQUE (plan_id, position)
) STRICT;

-- Frames of a plan: being published, committed, or quarantined in the rejected directory of their group.
CREATE TABLE dark_frames (
	plan_id TEXT NOT NULL,
	-- Id of the frame, unique in the plan.
	frame_id TEXT NOT NULL,
	group_id TEXT NOT NULL,
	-- Number of the frame among the files of its group, from 1, never reused.
	sequence INTEGER NOT NULL,
	-- publishing until its file is linked; committed counts; rejected never counts.
	state TEXT NOT NULL CHECK (state IN ('publishing', 'committed', 'rejected')),
	-- Order in which the frame was committed or rejected within its plan, from 1; NULL while publishing.
	position INTEGER,
	-- Outcome of its examination (DarkFrameVerdict).
	verdict TEXT NOT NULL CHECK (verdict IN ('accepted', 'acceptedWithWarnings', 'rejected', 'incomplete')),
	-- Absolute path of its file, and the one it was staged at while it could still be there (NULL otherwise).
	path TEXT NOT NULL,
	staged_path TEXT,
	-- Size of its file in bytes, and when its exposure started, Unix milliseconds (UTC).
	size INTEGER NOT NULL,
	time INTEGER NOT NULL,
	-- What its examination measured (DarkFrameAssessment with its planes, header, temperature trace, acknowledgement,
	-- and the reason it never was examined).
	assessment TEXT NOT NULL CHECK (json_valid(assessment)),
	PRIMARY KEY (plan_id, frame_id),
	UNIQUE (plan_id, group_id, sequence),
	UNIQUE (plan_id, position),
	FOREIGN KEY (plan_id, group_id) REFERENCES dark_groups (plan_id, group_id) ON DELETE CASCADE
) STRICT;

-- Frames of the Calibration Library (CalibrationLibraryStore), by reference: frames of the Dark Library plans, frames
-- the Flat Wizard published, and imported files. What an operator declared (an override, a role, an exclusion) is the
-- current state of the row. Kept until an operator deletes the frame with its file.
CREATE TABLE calibration_sources (
	-- Stable id, derived from its path.
	source_id TEXT PRIMARY KEY,
	-- Id of its group, and its compatibility key.
	group_id TEXT NOT NULL,
	key TEXT NOT NULL,
	-- Role (CalibrationKind).
	kind TEXT NOT NULL,
	-- Hardware id of its camera; empty when unknown.
	camera_id TEXT NOT NULL,
	-- State of its file.
	status TEXT NOT NULL CHECK (status IN ('available', 'missing', 'changed', 'corrupt')),
	-- Name of its file in lower case, for ordering and search.
	name TEXT NOT NULL,
	-- Where it came from, and the plan, session, or import it came from (NULL when none).
	origin TEXT NOT NULL CHECK (origin IN ('darkPlan', 'flatWizard', 'import')),
	origin_id TEXT,
	-- Absolute path and format of its file; never published in an event or a list.
	path TEXT NOT NULL,
	format TEXT NOT NULL CHECK (format IN ('fits', 'xisf')),
	-- Size in bytes and modification time in Unix milliseconds of its file when indexed, and its SHA-256 once a job read
	-- it at that size and time (NULL before).
	bytes INTEGER NOT NULL,
	mtime_ms REAL NOT NULL,
	digest TEXT,
	-- Why an operator left it out of masters; NULL when included.
	excluded_reason TEXT,
	-- Frames its plan required in its group; NULL without a plan.
	required INTEGER,
	-- Whether a master can read it at all (0 or 1).
	supported INTEGER NOT NULL CHECK (supported IN (0, 1)),
	-- What is known about it, each value with its evidence (CalibrationMetadata), and what should be said about it: [text].
	metadata TEXT NOT NULL CHECK (json_valid(metadata)),
	warnings TEXT NOT NULL CHECK (json_valid(warnings))
) STRICT;

CREATE INDEX calibration_sources_group ON calibration_sources (group_id);
CREATE INDEX calibration_sources_filter ON calibration_sources (kind, camera_id, status);

-- Masters of the Calibration Library: the highest revision each one ever had, so a number is never used again, even
-- after its revision was deleted or a crash interrupted its publication.
CREATE TABLE calibration_masters (
	master_id TEXT PRIMARY KEY,
	last_revision INTEGER NOT NULL
) STRICT;

-- Revisions of the masters. A revision is publishing from the moment its number is taken until its directory is in
-- products/, and deleting from the moment an operator deletes it until its directory is gone; the start reconciles both
-- from the disk. Only published revisions are listed. Its FITS file is products/<masterId>/vNNNN/master.fit.
CREATE TABLE calibration_revisions (
	master_id TEXT NOT NULL REFERENCES calibration_masters (master_id),
	-- Revision, from 1.
	revision INTEGER NOT NULL,
	publication TEXT NOT NULL CHECK (publication IN ('publishing', 'published', 'deleting')),
	-- State now, and the one it was published with, which it returns to when what made it unavailable or stale is gone.
	status TEXT NOT NULL CHECK (status IN ('ready', 'warning', 'stale', 'unavailable')),
	published_status TEXT NOT NULL CHECK (published_status IN ('ready', 'warning')),
	-- Role, camera hardware id and filter name (empty when unknown), id and compatibility key of its group.
	kind TEXT NOT NULL,
	camera_id TEXT NOT NULL,
	filter TEXT NOT NULL,
	group_id TEXT NOT NULL,
	key TEXT NOT NULL,
	-- Identity of its inputs and recipe, which a repeated request answers with.
	fingerprint TEXT NOT NULL,
	-- When it was published, Unix milliseconds (UTC).
	created_at INTEGER NOT NULL,
	-- SHA-256 and size in bytes of its FITS file.
	content_digest TEXT NOT NULL,
	bytes INTEGER NOT NULL,
	-- The rest of the master (CalibrationMaster): what its pixels contain, units, usage, full scale in DN, recipe,
	-- metadata, diagnostics, and what an operator accepted.
	master TEXT NOT NULL CHECK (json_valid(master)),
	PRIMARY KEY (master_id, revision)
) STRICT;

CREATE INDEX calibration_revisions_fingerprint ON calibration_revisions (fingerprint);

-- Frames of a revision, in integration order, with what the job read; a frame deleted later stays named here.
CREATE TABLE calibration_revision_sources (
	master_id TEXT NOT NULL,
	revision INTEGER NOT NULL,
	-- Order of the frame in the integration, from 0.
	position INTEGER NOT NULL,
	source_id TEXT NOT NULL,
	-- SHA-256 of the frame as the job read it, and the name of its file.
	digest TEXT NOT NULL,
	name TEXT NOT NULL,
	PRIMARY KEY (master_id, revision, position),
	FOREIGN KEY (master_id, revision) REFERENCES calibration_revisions (master_id, revision) ON DELETE CASCADE
) STRICT;

-- Masters a revision was corrected with. A revision another one depends on cannot be deleted.
CREATE TABLE calibration_revision_dependencies (
	master_id TEXT NOT NULL,
	revision INTEGER NOT NULL,
	-- Order of the dependency, from 0.
	position INTEGER NOT NULL,
	dependency_master_id TEXT NOT NULL,
	dependency_revision INTEGER NOT NULL,
	-- SHA-256 of the FITS file of the dependency when it was used.
	digest TEXT NOT NULL,
	PRIMARY KEY (master_id, revision, position),
	FOREIGN KEY (master_id, revision) REFERENCES calibration_revisions (master_id, revision) ON DELETE CASCADE,
	FOREIGN KEY (dependency_master_id, dependency_revision) REFERENCES calibration_revisions (master_id, revision) ON DELETE RESTRICT
) STRICT;

CREATE INDEX calibration_revision_dependencies_target ON calibration_revision_dependencies (dependency_master_id, dependency_revision);

-- The revision an operator prefers for each master; it goes with that revision.
CREATE TABLE calibration_preferred (
	master_id TEXT PRIMARY KEY,
	revision INTEGER NOT NULL,
	FOREIGN KEY (master_id, revision) REFERENCES calibration_revisions (master_id, revision) ON DELETE CASCADE
) STRICT;

-- Projects of Image Stacking (ImageStackingStore): one intended target or field, the light frames chosen for it, and
-- what an operator decided about them. Kept until an operator deletes the project; its frames stay on the disk.
CREATE TABLE stack_projects (
	-- Id of the project, generated by the server.
	project_id TEXT PRIMARY KEY,
	-- Name an operator gave it.
	name TEXT NOT NULL,
	-- Revision of its header, increased by every rename; >= 1.
	revision INTEGER NOT NULL CHECK (revision > 0),
	-- When it was created and last changed (its header, frames, or filter aliases), Unix milliseconds (UTC).
	created_at INTEGER NOT NULL,
	updated_at INTEGER NOT NULL,
	-- Choices of an operator (StackingSettings): the pinned project reference group, the pinned reference frame of each
	-- group, and the quality thresholds of the selection.
	settings TEXT NOT NULL CHECK (json_valid(settings)),
	-- Outcome of the latest registration (StackingProjectAnalysis): the reference of each group and its transform onto
	-- the project reference; NULL before the first analysis.
	analysis TEXT CHECK (analysis IS NULL OR json_valid(analysis))
) STRICT;

-- Light frames of a project, by reference: files are never written, moved, or copied. One file joins a project once,
-- under whichever name it was found first.
CREATE TABLE stack_sources (
	-- Stable id, derived from its project and path.
	source_id TEXT PRIMARY KEY,
	project_id TEXT NOT NULL REFERENCES stack_projects (project_id) ON DELETE CASCADE,
	-- Absolute path and format of its file; never published in an event or a list.
	path TEXT NOT NULL,
	format TEXT NOT NULL CHECK (format IN ('fits', 'xisf')),
	-- Identity of the file (device:inode, or its real path where inodes are not reported).
	identity TEXT NOT NULL,
	-- Name of its file in lower case, for ordering and search.
	name TEXT NOT NULL,
	-- Size in bytes and modification time in Unix milliseconds of its file when indexed, and its SHA-256 once a job read
	-- it at that size and time (NULL before).
	bytes INTEGER NOT NULL,
	mtime_ms REAL NOT NULL,
	digest TEXT,
	-- State of its file.
	status TEXT NOT NULL CHECK (status IN ('available', 'missing', 'changed', 'corrupt')),
	-- Role: a light, or a frame whose header says no role and waits for an operator.
	role TEXT NOT NULL CHECK (role IN ('light', 'unclassified')),
	-- Canonical key of its filter (empty when unknown), before the aliases of the project.
	filter_key TEXT NOT NULL,
	-- Key of the acquisition settings calibration masters must match.
	cohort_key TEXT NOT NULL,
	-- Target named by its header (OBJECT); empty when it names none.
	object TEXT NOT NULL,
	-- Start of its exposure, Unix milliseconds (UTC); NULL when the header does not say.
	observed_at INTEGER,
	-- Why an operator left it out of stacks; NULL when included.
	excluded_reason TEXT,
	-- What is known about it, each value with its evidence (CalibrationMetadata), and what should be said about it: [text].
	metadata TEXT NOT NULL CHECK (json_valid(metadata)),
	warnings TEXT NOT NULL CHECK (json_valid(warnings)),
	-- What the latest analysis measured (StackingFrameAnalysis): its fingerprint, SHA-256, quality, brightest stars in
	-- pixels, and transform onto the reference of its group; NULL before.
	analysis TEXT CHECK (analysis IS NULL OR json_valid(analysis)),
	UNIQUE (project_id, identity)
) STRICT;

CREATE INDEX stack_sources_project ON stack_sources (project_id, filter_key, name);

-- Filters an operator merged in a project: frames whose canonical filter key is filter_key belong to the group of
-- target_key. A target is never itself merged into another key.
CREATE TABLE stack_filter_aliases (
	project_id TEXT NOT NULL REFERENCES stack_projects (project_id) ON DELETE CASCADE,
	-- Canonical key merged, and the key of the group it joins.
	filter_key TEXT NOT NULL,
	target_key TEXT NOT NULL,
	PRIMARY KEY (project_id, filter_key)
) STRICT;

-- Calibration decisions of a project, one per cohort: the lights of one filter group sharing their acquisition settings.
-- A cohort whose frames are gone keeps its row until its project goes, so its decision returns with them.
CREATE TABLE stack_cohorts (
	project_id TEXT NOT NULL REFERENCES stack_projects (project_id) ON DELETE CASCADE,
	-- Id of the cohort, derived from its group key and acquisition key.
	cohort_id TEXT NOT NULL,
	-- Key of its filter group, and of its acquisition settings.
	group_key TEXT NOT NULL,
	cohort_key TEXT NOT NULL,
	-- Hardware id of the camera an operator declared, and why; NULL when undeclared.
	camera_id TEXT,
	camera_reason TEXT,
	-- Calibration chosen (StackingCalibration): pinned master revisions with their SHA-256, or none with a reason; NULL
	-- while undecided.
	calibration TEXT CHECK (calibration IS NULL OR json_valid(calibration)),
	PRIMARY KEY (project_id, cohort_id)
) STRICT;

-- Integrations of a project, in the order they were asked for. A run interrupted by the end of the process is marked so
-- on the next start; what it published stays.
CREATE TABLE stack_runs (
	run_id TEXT PRIMARY KEY,
	project_id TEXT NOT NULL REFERENCES stack_projects (project_id) ON DELETE CASCADE,
	-- Key the request was sent with, so a repeated request answers the same run.
	token TEXT NOT NULL,
	-- running, completed (every group published or reused), failed, cancelled, or interrupted.
	state TEXT NOT NULL CHECK (state IN ('running', 'completed', 'failed', 'cancelled', 'interrupted')),
	-- When it was asked for and when it ended, Unix milliseconds (UTC); ended_at is NULL while running.
	created_at INTEGER NOT NULL,
	ended_at INTEGER,
	-- How frames are combined (StackingRecipe).
	recipe TEXT NOT NULL CHECK (json_valid(recipe)),
	-- Outcome of each filter group (StackingRunGroup[]): the product it published or reused, or why it failed.
	groups TEXT NOT NULL CHECK (json_valid(groups)),
	-- Why it failed as a whole; NULL otherwise.
	error TEXT,
	UNIQUE (project_id, token)
) STRICT;

CREATE INDEX stack_runs_project ON stack_runs (project_id, created_at);

-- Linear masters of a project, one per filter group and integration, immutable once published: master.fit and
-- coverage.fit in products/<product_id>/ under the directory of Image Stacking. A product is publishing from the moment
-- its row is written until its directory is in products/, and deleting from the moment it is deleted until its directory
-- is gone, so a crash between the two halves is finished from the disk on the next start.
CREATE TABLE stack_products (
	product_id TEXT PRIMARY KEY,
	project_id TEXT NOT NULL REFERENCES stack_projects (project_id) ON DELETE CASCADE,
	-- Run that integrated it.
	run_id TEXT NOT NULL,
	publication TEXT NOT NULL CHECK (publication IN ('publishing', 'published', 'deleting')),
	-- Filter group, by key, and its name when integrated.
	group_key TEXT NOT NULL,
	name TEXT NOT NULL,
	-- Identity of its inputs (StackingProduct.fingerprint): an equal one is reused instead of integrated again.
	fingerprint TEXT NOT NULL,
	-- When it was published, Unix milliseconds (UTC).
	created_at INTEGER NOT NULL,
	-- SHA-256 and size, in bytes, of master.fit and coverage.fit.
	content_digest TEXT NOT NULL,
	bytes INTEGER NOT NULL CHECK (bytes > 0),
	coverage_digest TEXT NOT NULL,
	coverage_bytes INTEGER NOT NULL CHECK (coverage_bytes > 0),
	-- Everything else about it (StackingProduct): grid, frames, exposure, recipe, calibration pins, and diagnostics.
	product TEXT NOT NULL CHECK (json_valid(product))
) STRICT;

CREATE INDEX stack_products_project ON stack_products (project_id, created_at);
CREATE INDEX stack_products_fingerprint ON stack_products (project_id, fingerprint);

-- Light frames a product integrated, with the SHA-256 and weight each had. A frame later removed from its project or
-- changed leaves the product stale, never deleted.
CREATE TABLE stack_product_sources (
	product_id TEXT NOT NULL REFERENCES stack_products (product_id) ON DELETE CASCADE,
	source_id TEXT NOT NULL,
	digest TEXT NOT NULL,
	-- Combination weight, positive.
	weight REAL NOT NULL CHECK (weight > 0),
	PRIMARY KEY (product_id, source_id)
) STRICT;

-- Color composites of a project, mixed from its linear masters and never from light frames, immutable once published:
-- composite.fit in composites/<composite_id>/ under the directory of Image Stacking. A composite is publishing until its
-- directory is in composites/, and deleting until it is gone, so a crash between the two halves is finished on start.
CREATE TABLE stack_composites (
	composite_id TEXT PRIMARY KEY,
	project_id TEXT NOT NULL REFERENCES stack_projects (project_id) ON DELETE CASCADE,
	publication TEXT NOT NULL CHECK (publication IN ('publishing', 'published', 'deleting')),
	-- Identity of its inputs (StackingComposite.fingerprint): an equal one is reused instead of composed again.
	fingerprint TEXT NOT NULL,
	-- When it was published, Unix milliseconds (UTC).
	created_at INTEGER NOT NULL,
	-- SHA-256 and size, in bytes, of composite.fit.
	content_digest TEXT NOT NULL,
	bytes INTEGER NOT NULL CHECK (bytes > 0),
	-- Everything else about it (StackingComposite): its composition, crop, and diagnostics.
	composite TEXT NOT NULL CHECK (json_valid(composite))
) STRICT;

CREATE INDEX stack_composites_project ON stack_composites (project_id, created_at);

-- Masters a composite was mixed from. A master stays while a composite depends on it: the reference is checked at the
-- end of each statement, so deleting a project with both goes through and deleting only the master does not.
CREATE TABLE stack_composite_sources (
	composite_id TEXT NOT NULL REFERENCES stack_composites (composite_id) ON DELETE CASCADE,
	product_id TEXT NOT NULL REFERENCES stack_products (product_id),
	PRIMARY KEY (composite_id, product_id)
) STRICT;

CREATE INDEX stack_composite_sources_product ON stack_composite_sources (product_id);
