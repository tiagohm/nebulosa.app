import type { AppDatabase } from './database'
import { errorResponse } from './http'
import type { FieldObjects, FieldQuery } from './sky/catalog'

// Framings of the Framing tool (table framings): the telescope and camera a field of view is computed from and the
// rotation of the sensor, one catalog shared by every profile, tab, and browser. A framing never holds a position on
// the sky: a tool that needs one asks for it itself. Each framing is written whole from the revision it was edited
// from, so a change another tab saved first is refused with what the server kept, and every committed write is
// published. The field of its preview (the catalog objects of a cone) is answered here too.

// Camera role of an Equipment Setup a framing can follow.
export type FramingCameraRole = 'MAIN_CAMERA' | 'GUIDE_CAMERA'

// Optics of an Equipment Setup a framing can follow: the telescope or the guide telescope.
export type FramingSetupOptics = 'telescope' | 'guideTelescope'

// Where a telescope or camera of a framing comes from: typed by hand, copied from a model of the AstroBin equipment
// database, the item of the Equipment Catalog it refers to, or the Equipment Setup of the active profile of the tab.
export type FramingOpticsSource = 'manual' | 'model' | 'catalog' | 'setup'

// Sensor of a framing: its pixel grid and pitch, or only its physical size.
export type FramingSensor =
	| {
			// Sensor given by its pixels.
			readonly kind: 'pixels'
			// Width, in pixels.
			readonly width: number
			// Height, in pixels.
			readonly height: number
			// Pixel size, in micrometers.
			readonly pixelSize: number
	  }
	| {
			// Sensor given by its physical size.
			readonly kind: 'physical'
			// Width, in millimeters.
			readonly width: number
			// Height, in millimeters.
			readonly height: number
	  }

// Telescope of a framing. The values are the ones last typed or copied: a catalog or setup source resolves them again
// from what it refers to, and keeps these for what it does not declare or when it no longer exists.
export interface FramingTelescope {
	// Where it comes from.
	readonly source: FramingOpticsSource
	// Telescope of the Equipment Catalog of a catalog source.
	readonly telescopeId?: string
	// Optics of the Equipment Setup of a setup source.
	readonly setupOptics?: FramingSetupOptics
	// Model of the AstroBin equipment database of a model source, as the catalog names it.
	readonly model?: string
	// Native focal length, in millimeters; 0 when unknown.
	readonly focalLength: number
	// Clear aperture, in millimeters; 0 when unknown.
	readonly aperture: number
	// Factor of the reducer or Barlow in the light path, always the framing's own; 1 without one.
	readonly focalMultiplier: number
}

// Camera of a framing. The sensor is the one last typed or copied: a catalog or setup source resolves it again from
// what it refers to, and keeps it for what it does not declare or when it no longer exists.
export interface FramingCamera {
	// Where it comes from.
	readonly source: FramingOpticsSource
	// Camera of the Equipment Catalog of a catalog source.
	readonly cameraId?: string
	// Camera role of the Equipment Setup of a setup source.
	readonly role?: FramingCameraRole
	// Model of the AstroBin equipment database of a model source, as the catalog names it.
	readonly model?: string
	// Sensor.
	readonly sensor: FramingSensor
}

// Optics of a framing.
export interface FramingOptics {
	// Telescope.
	readonly telescope: FramingTelescope
	// Camera.
	readonly camera: FramingCamera
}

// Content of a framing, as the operator edits it.
export interface FramingDocument {
	// Name shown to people, unique without regard to case.
	readonly name: string
	// Telescope and camera.
	readonly optics: FramingOptics
	// Position angle of the top edge of the sensor, north through east, in degrees in [0, 360).
	readonly rotation: number
}

// Saved framing.
export interface Framing extends FramingDocument {
	// Id, generated by the tab that created it.
	readonly id: string
	// Revision, increased by every save; >= 1.
	readonly revision: number
	// When it was created, Unix milliseconds (UTC).
	readonly createdAt: number
	// When it was last changed, Unix milliseconds (UTC).
	readonly updatedAt: number
}

// Answer of GET /api/framings.
export interface FramingsSnapshot {
	// Every framing, by name.
	readonly framings: readonly Framing[]
}

// Body of PUT /api/framings/:id: the whole document and the revision it was edited from (0 creates it).
export interface FramingSaveRequest extends FramingDocument {
	// Revision the tab last saw; 0 for a new framing.
	readonly revision: number
}

// Body of POST /api/framings/:id/duplicate.
export interface FramingDuplicateRequest {
	// Id of the copy, generated by the tab.
	readonly id: string
	// Name of the copy.
	readonly name: string
}

// Body of POST /api/framings/field: the cone of a preview, around a J2000 center.
export interface FramingFieldRequest {
	// Right ascension of the center (ICRS), in radians.
	readonly rightAscension: number
	// Declination of the center, in radians.
	readonly declination: number
	// Radius of the cone, in radians, in (0, π/2).
	readonly radius: number
}

// Answer of POST /api/framings/field: the catalog objects of the cone and the faintest magnitude it kept.
export interface FramingField extends FieldObjects {
	// Faintest star magnitude kept for the radius (FIELD_MAGNITUDE_LIMIT).
	readonly magnitudeLimit: number
}

// Codes of the errors of the framing routes.
export type FramingErrorCode = 'conflict' | 'notFound' | 'nameTaken'

// Outcome of a write: saved, refused because another revision was saved since (with the current framing, null when it
// no longer exists), refused because another framing has the name, or refused because the framing does not exist.
export type FramingOutcome = { readonly status: 'saved'; readonly framing: Framing } | { readonly status: 'conflict'; readonly current: Framing | null } | { readonly status: 'nameTaken' } | { readonly status: 'notFound' }

// Outcome of a removal.
export type FramingRemoval = { readonly status: 'removed' } | { readonly status: 'conflict'; readonly current: Framing } | { readonly status: 'notFound' }

// Change of a framing, published once its transaction committed.
export type FramingEvent =
	// A framing was created, edited, or duplicated; carries the whole saved framing.
	| { readonly type: 'framing:updated'; readonly framing: Framing }
	// A framing was deleted.
	| { readonly type: 'framing:removed'; readonly id: string }

// Most stars a field keeps, the brightest ones: enough to fill the widest preview without drawing a blur.
export const FIELD_MAX_STARS = 3000

// Most deep-sky objects a field keeps, the brightest ones.
export const FIELD_MAX_DEEP_SKY = 300

// Faintest star magnitude a field keeps for a cone radius in radians: magnitude 9 for a radius of 1°, half a magnitude
// fainter each time the radius is divided by about 1.6 (2.5·log₁₀ of the radius in degrees), clamped to magnitudes 6 to
// 14, so a narrow field still shows stars and a wide one is not drowned in them.
export function fieldMagnitudeLimit(radius: number) {
	return Math.min(14, Math.max(6, 9 - 2.5 * Math.log10((radius * 180) / Math.PI)))
}

// Row of a framing.
interface FramingRow {
	readonly id: string
	readonly name: string
	readonly optics: string
	readonly rotation: number
	readonly revision: number
	readonly createdAt: number
	readonly updatedAt: number
}

// Columns of a framing, named as the API names them.
const FRAMING_COLUMNS = 'id, name, optics, rotation, revision, created_at AS createdAt, updated_at AS updatedAt'

// Returns the framing of a row.
function framingOf({ optics, ...row }: FramingRow): Framing {
	return { ...row, optics: JSON.parse(optics) as FramingOptics }
}

// Framings of the operational database.
export class FramingStore {
	// Creates the store over database.
	constructor(readonly database: AppDatabase) {}

	// Returns every framing, by name without regard to case.
	list(): Framing[] {
		return this.database.db.query<FramingRow, []>(`SELECT ${FRAMING_COLUMNS} FROM framings ORDER BY name, id`).all().map(framingOf)
	}

	// Returns a framing; undefined when it does not exist.
	get(id: string): Framing | undefined {
		const row = this.database.db.query<FramingRow, [string]>(`SELECT ${FRAMING_COLUMNS} FROM framings WHERE id = ?`).get(id)
		return row ? framingOf(row) : undefined
	}

	// Saves a whole framing when `revision` is the one stored (0 creates it), increasing the revision; nameTaken when
	// another framing has the name.
	save(id: string, request: FramingSaveRequest, now: number = Date.now()): FramingOutcome {
		return this.database.write((): FramingOutcome => {
			const current = this.get(id)
			if ((current?.revision ?? 0) !== request.revision) return { status: 'conflict', current: current ?? null }
			if (this.#nameTaken(request.name, id)) return { status: 'nameTaken' }
			this.#write(id, request, current ? current.revision + 1 : 1, current?.createdAt ?? now, now)
			return { status: 'saved', framing: this.get(id)! }
		})
	}

	// Copies a framing under a new id and name, as revision 1; nameTaken when another framing has the name, conflict when
	// the new id is taken.
	duplicate(id: string, newId: string, name: string, now: number = Date.now()): FramingOutcome {
		return this.database.write((): FramingOutcome => {
			const source = this.get(id)
			if (!source) return { status: 'notFound' }
			const taken = this.get(newId)
			if (taken) return { status: 'conflict', current: taken }
			if (this.#nameTaken(name, newId)) return { status: 'nameTaken' }
			this.#write(newId, { ...source, name }, 1, now, now)
			return { status: 'saved', framing: this.get(newId)! }
		})
	}

	// Removes a framing when `revision` is the one stored.
	remove(id: string, revision: number): FramingRemoval {
		return this.database.write((): FramingRemoval => {
			const current = this.get(id)
			if (!current) return { status: 'notFound' }
			if (current.revision !== revision) return { status: 'conflict', current }
			this.database.db.query('DELETE FROM framings WHERE id = ?').run(id)
			return { status: 'removed' }
		})
	}

	// Whether a framing other than id has the name, without regard to case.
	#nameTaken(name: string, id: string) {
		return this.database.db.query('SELECT 1 FROM framings WHERE name = ? COLLATE NOCASE AND id <> ?').get(name.trim(), id) !== null
	}

	// Writes a framing row; runs inside a transaction.
	#write(id: string, { name, optics, rotation }: FramingDocument, revision: number, createdAt: number, updatedAt: number) {
		this.database.db
			.query('INSERT INTO framings (id, name, optics, rotation, revision, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?) ON CONFLICT (id) DO UPDATE SET name = excluded.name, optics = excluded.optics, rotation = excluded.rotation, revision = excluded.revision, updated_at = excluded.updated_at')
			.run(id, name.trim(), JSON.stringify(optics), rotation, revision, createdAt, updatedAt)
	}
}

// Options of the framing service.
export interface FramingServiceOptions {
	// Store of the framings.
	readonly store: FramingStore
	// Catalog objects of a cone (the stars and deep-sky objects of the sky catalog, J2000).
	readonly field: (query: FieldQuery) => FieldObjects
	// Receives every committed change.
	readonly listener?: (event: FramingEvent) => void
}

// Framings and the field of their preview.
export class FramingService {
	// Creates the service.
	constructor(readonly options: FramingServiceOptions) {}

	// Every framing.
	framings(): FramingsSnapshot {
		return { framings: this.options.store.list() }
	}

	// Saves a whole framing when the revision matches, publishing it once committed.
	save(id: string, request: FramingSaveRequest) {
		return this.#published(this.options.store.save(id, request))
	}

	// Copies a framing under a new id and name, publishing the copy once committed.
	duplicate(id: string, { id: newId, name }: FramingDuplicateRequest) {
		return this.#published(this.options.store.duplicate(id, newId, name))
	}

	// Deletes a framing when the revision matches, publishing the removal once committed.
	remove(id: string, revision: number) {
		const outcome = this.options.store.remove(id, revision)
		if (outcome.status === 'removed') this.options.listener?.({ type: 'framing:removed', id })
		return outcome
	}

	// Stars and deep-sky objects of the cone of a preview, J2000, stars moved by their proper motion to now, down to the
	// magnitude fieldMagnitudeLimit gives for its radius.
	field({ rightAscension, declination, radius }: FramingFieldRequest, now: number = Date.now()): FramingField {
		const magnitudeLimit = fieldMagnitudeLimit(radius)
		return { ...this.options.field({ rightAscension, declination, radius, time: now, magnitudeLimit, maxStars: FIELD_MAX_STARS, maxDeepSky: FIELD_MAX_DEEP_SKY }), magnitudeLimit }
	}

	// Publishes a saved framing.
	#published(outcome: FramingOutcome) {
		if (outcome.status === 'saved') this.options.listener?.({ type: 'framing:updated', framing: outcome.framing })
		return outcome
	}
}

// Answers a write of a framing: the saved framing, 409 conflict with the current one, 409 nameTaken, or 404.
function framingResponse(outcome: FramingOutcome | Exclude<FramingRemoval, { status: 'removed' }>): Response {
	if (outcome.status === 'saved') return Response.json(outcome.framing)
	if (outcome.status === 'conflict') return errorResponse('The framing was changed by another tab', 409, 'conflict' satisfies FramingErrorCode, { framing: outcome.current })
	if (outcome.status === 'nameTaken') return errorResponse('Another framing has this name', 409, 'nameTaken' satisfies FramingErrorCode)
	return errorResponse('Framing not found', 404, 'notFound' satisfies FramingErrorCode)
}

// Routes of the framings.
export function createFramingRoutes(service: FramingService) {
	return {
		'/api/framings': {
			// Every framing (FramingsSnapshot).
			GET: () => Response.json(service.framings()),
		},
		'/api/framings/field': {
			// Catalog objects of the cone of a preview (FramingField) for the body (FramingFieldRequest).
			POST: async (req) => Response.json(service.field((await req.json()) as FramingFieldRequest)),
		},
		'/api/framings/:id': {
			// Saves the whole framing of the body (FramingSaveRequest, revision 0 creating it); 409 conflict with the current
			// framing (null when it was deleted) when another revision was saved since, 409 nameTaken.
			PUT: async (req) => framingResponse(service.save(req.params.id, (await req.json()) as FramingSaveRequest)),
			// Deletes the framing of ?revision; 409 conflict with the current framing when another revision was saved since; 404.
			DELETE: (req) => {
				const outcome = service.remove(req.params.id, +new URL(req.url).searchParams.get('revision')!)
				return outcome.status === 'removed' ? new Response(undefined, { status: 204 }) : framingResponse(outcome)
			},
		},
		'/api/framings/:id/duplicate': {
			// Copies the framing under the id and name of the body (FramingDuplicateRequest); 404 when it does not exist, 409
			// nameTaken, 409 conflict when the new id is taken.
			POST: async (req) => framingResponse(service.duplicate(req.params.id, (await req.json()) as FramingDuplicateRequest)),
		},
	} as const satisfies Bun.Serve.Routes<undefined, string>
}
